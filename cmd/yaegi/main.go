// Command yaegi runs a Go main package (a .go file, a directory or an import
// path) in the prototype VM: go/packages + go/types + go/ssa front-end,
// uniform Value representation, register-based bytecode, explicit frame stack.
//
// Arguments after the program are passed to it in os.Args, and the program
// gets a fresh flag.CommandLine.
//
// Exit codes: 0 success, 2 unrecovered panic, 3 construct not supported by
// the VM, 4 load, parse or type error. A program calling os.Exit keeps its code.
package main

import (
	"errors"
	"flag"
	"fmt"
	"os"
	"strings"

	_ "github.com/traefik/yaegi/v2/aot/all"            // AOT copies generated by cmd/aotgen (-aot, -mode p=aot)
	_ "github.com/traefik/yaegi/v2/natsyms/all"        // native symbol tables of non-std packages (-mode p=native)
	_ "github.com/traefik/yaegi/v2/stdsyms/sideeffect" // expvar, net/http/pprof and testing/quick, as with "go run"
	"github.com/traefik/yaegi/v2/vm"
)

func main() {
	// yaegi's own flags live outside flag.CommandLine, which belongs to the
	// interpreted program (it calls the native flag package).
	flags := flag.NewFlagSet("yaegi", flag.ExitOnError)
	budget := flags.Int64("budget", 0, "max calls+back-jumps (0: unlimited)")
	stats := flags.Bool("stats", false, "print load/run timings to stderr (also when the program calls os.Exit; not when it ends with log.Fatal)")
	src := flags.String("src", "", "comma-separated packages to interpret from source instead of calling natively (\"all\": every package outside the native floor)")
	opaque := flags.Bool("opaque", false, "pass interpreted values to native `any` parameters as opaque handles (enables the VM reflect; implied by -aot)")
	tags := flags.String("tags", "", "comma-separated build tags, as go run -tags")
	yaegiTags := flags.Bool("yaegi-tags", false, "also use the build tags of the program's \"// yaegi:tags t1 t2\" comment lines, as yaegi does (go ignores them)")
	aot := flags.Bool("aot", false, "run the packages compiled ahead of time by cmd/aotgen (aot/...) in AOT mode")
	staleAOT := flags.Bool("allow-stale-aot", false, "with -aot: accept AOT copies made with an older patch release of the Go release of yaegi v2 (they miss its standard library fixes)")
	aotFallback := flags.Bool("stale-aot-fallback", false, "with -aot: when the AOT copies cannot run with the Go version of yaegi v2, run in default mode instead of failing (a warning goes to stderr)")
	modes := flags.String("mode", "", "per import path mode: path=native|aot|interp,... (overrides -aot and -src)")
	restricted := flags.Bool("restricted", false, "apply the import restrictions of Traefik plugins: refuse os/exec and plugin, and unsafe and syscall without -unsafe")
	useUnsafe := flags.Bool("unsafe", false, "with -restricted: allow unsafe and syscall (Traefik's useUnsafe)")
	restrictedStd := flags.Bool("restrictedstd", false, "use the standard library of plugins (yaegi's restricted stdlib: os.Exit and log.Fatal panic, no os/exec and syscall) without the import restrictions of -restricted (implied by -restricted)")
	execMode := flags.String("exec", "", "with -restricted or -restrictedstd: os/exec for the program: mock (it loads, running a program returns an error) or real (programs run, as in Go)")
	printStdout := flags.Bool("print-stdout", false, "write the output of the print and println builtins to stdout, like yaegi (default: stderr, like gc)")
	eval := flags.String("e", "", "run this Go source (declarations and statements, imports of the standard library) instead of a program, and print the value of a last expression")
	interactive := flags.Bool("i", false, "read Go source from the standard input, one input at a time (a REPL), instead of running a program")
	flags.Usage = func() {
		fmt.Fprintf(flags.Output(), "usage: yaegi [flags] <file.go|dir|import path> [args...]\n       yaegi [flags] -e <source>\n       yaegi [flags] -i\n")
		flags.PrintDefaults()
	}
	_ = flags.Parse(os.Args[1:])
	if *eval != "" || *interactive {
		eo := evalOptions(*budget, *restricted, *useUnsafe, *aot, *staleAOT, *printStdout)
		eo.StaleAOTFallback = *aotFallback
		os.Exit(runEval(eo, *eval, *interactive))
	}
	if flags.NArg() < 1 {
		flags.Usage()
		os.Exit(2)
	}
	os.Args = flags.Args()
	flag.CommandLine = flag.NewFlagSet(os.Args[0], flag.ExitOnError)

	opts := vm.RunOptions{Budget: *budget, OpaqueAny: *opaque, AOT: *aot, AllowStaleAOT: *staleAOT, StaleAOTFallback: *aotFallback, YaegiTags: *yaegiTags, Restricted: *restricted, UseUnsafe: *useUnsafe, RestrictedStd: *restrictedStd}
	if *printStdout {
		opts.PrintOut = os.Stdout
	}
	opts.OnStaleAOT = func(note string) { fmt.Fprintf(os.Stderr, "yaegi: warning: %s\n", note) }
	switch *execMode {
	case "":
	case "mock":
		opts.Exec = vm.ExecMock
	case "real":
		opts.Exec = vm.ExecReal
	default:
		fmt.Fprintln(os.Stderr, "yaegi: -exec must be mock or real")
		os.Exit(2)
	}
	if *modes != "" {
		md, err := vm.ParseModes(*modes)
		if err != nil {
			fmt.Fprintln(os.Stderr, "yaegi:", err)
			os.Exit(2)
		}
		opts.Modes = md
	}
	if *src != "" {
		opts.Src = strings.Split(*src, ",")
	}
	if *tags != "" {
		opts.Tags = strings.Split(*tags, ",")
	}
	printStats := func(tm vm.Timings) {
		if *stats {
			fmt.Fprintf(os.Stderr, "load+ssa: %v, run: %v\n", tm.Load, tm.Run)
		}
	}
	// The real os.Exit of the program ends yaegi v2 inside RunMain.
	opts.BeforeExit = func(_ int, tm vm.Timings) { printStats(tm) }
	tm, err := vm.RunMain(opts, os.Args[0])
	printStats(tm)
	var ge *vm.GoexitError
	if errors.As(err, &ge) {
		// The main goroutine of the program called runtime.Goexit: as
		// with gc, the program runs until its other goroutines end, then
		// stops with a fatal error. (yaegi v2 cannot leave this to the Go
		// runtime: it does not see the deadlock in a cgo binary.)
		ge.Wait()
		fmt.Fprintln(os.Stderr, "fatal error: no goroutines (main called runtime.Goexit) - deadlock!")
		os.Exit(2)
	}
	os.Exit(exitCode(err))
}

func exitCode(err error) int {
	var (
		le *vm.LoadError
		ce *vm.CompileError
		pe *vm.PanicError
	)
	switch {
	case err == nil:
		return 0
	case errors.As(err, &ce):
		fmt.Fprintln(os.Stderr, "yaegi:", ce.Msg)
		return 3
	case errors.As(err, &le):
		fmt.Fprintln(os.Stderr, le.Msg)
		return 4
	case errors.As(err, &pe):
		fmt.Fprintln(os.Stderr, pe.Error())
		if pe.Trace != "" {
			fmt.Fprint(os.Stderr, "\n", pe.Trace)
		}
		return 2
	default:
		fmt.Fprintln(os.Stderr, err)
		return 2
	}
}
