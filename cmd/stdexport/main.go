// Command stdexport writes the type information of the standard library
// (gc export data, one entry per package) for stdtypes.Platforms, as
// the files embedded by package stdtypes. It needs the Go toolchain; the VM
// that embeds its output does not.
//
// The data follows the Go release it is generated with: its files have the
// release in their name (go1_26_data_linux_amd64.go, go1_26_std_linux_amd64.gz)
// and are only built by that release ("go1.26 && !go1.27"). The data of
// each release of the window of yaegi v2 (gorelease.Window) is kept side by
// side: a run writes the files of its release only. release_guard.go stops
// the build on a release outside the window (see internal/gorelease).
//
//	go generate ./stdtypes     # runs: go run ../cmd/stdexport -out .
package main

import (
	"bytes"
	"compress/gzip"
	"flag"
	"fmt"
	"go/token"
	"io/fs"
	"net/url"
	"os"
	"os/exec"
	"path/filepath"
	"runtime"
	"slices"
	"sort"
	"strings"

	"golang.org/x/tools/go/gcexportdata"
	"golang.org/x/tools/go/packages"

	"github.com/traefik/yaegi/v2/internal/gorelease"
	"github.com/traefik/yaegi/v2/internal/stdsrc"
)

// srcPkgs are the packages whose sources are embedded too (see
// stdtypes.Universe.Source): the packages that the VM runs from source
// (internal/stdsrc).
var srcPkgs = stdsrc.All()

func main() {
	out := flag.String("out", "stdtypes", "output directory")
	flag.Parse()
	release, err := gorelease.Constraint(runtime.Version())
	if err != nil {
		fmt.Fprintf(os.Stderr, "stdexport: %v\n", err)
		os.Exit(1)
	}
	prefix = gorelease.Prefix(runtime.Version())
	// The files of the releases outside the window go (the files of this
	// release are written again below).
	old, _ := filepath.Glob(filepath.Join(*out, "go1_*"))
	for _, f := range old {
		if gorelease.OutsideWindow(f) {
			os.Remove(f)
		}
	}
	nm, err := exec.Command("go", "tool", "-n", "nm").Output()
	if err != nil {
		fmt.Fprintf(os.Stderr, "stdexport: go tool -n nm: %v\n", err)
		os.Exit(1)
	}
	for _, pl := range gorelease.Platforms {
		goos, goarch, _ := strings.Cut(pl, "/")
		if err := write(*out, goos, goarch, release, strings.TrimSpace(string(nm))); err != nil {
			fmt.Fprintf(os.Stderr, "stdexport %s: %v\n", pl, err)
			os.Exit(1)
		}
	}
	if err := writePaths(*out, release); err != nil {
		fmt.Fprintf(os.Stderr, "stdexport: %v\n", err)
		os.Exit(1)
	}
	if err := writeOther(*out, release); err != nil {
		fmt.Fprintf(os.Stderr, "stdexport: %v\n", err)
		os.Exit(1)
	}
}

// prefix starts the names of the files of the release of the toolchain:
// "go1_26".
var prefix string

// writeOther writes data_other.go, the empty data of the other platforms
// (stdtypes.Available is false there), and release_guard.go. Both are for
// the whole window of releases.
func writeOther(dir, _ string) error {
	var ps []string
	for _, pl := range gorelease.Platforms {
		goos, goarch, _ := strings.Cut(pl, "/")
		ps = append(ps, fmt.Sprintf("!(%s && %s)", goos, goarch))
	}
	src := fmt.Sprintf(`// Code generated by cmd/stdexport. DO NOT EDIT.

//go:build !(%s) || (%s)

package stdtypes

// No embedded data for this platform (see cmd/stdexport): Available is false.
// On a Go release outside the window, release_guard.go stops the build.
var data []byte
`, gorelease.WindowConstraint(), strings.Join(ps, " && "))
	if err := os.WriteFile(filepath.Join(dir, "data_other.go"), []byte(src), 0o644); err != nil {
		return err
	}
	guard := gorelease.Guard("cmd/stdexport", "github.com/traefik/yaegi/v2/stdtypes", "go generate ./stdtypes ./stdsyms && sh scripts/aotgen.sh, with the toolchain of each release")
	return os.WriteFile(filepath.Join(dir, "release_guard.go"), guard, 0o644)
}

// writePaths writes go1_NN_data_packages.go, the import paths of all the packages
// of the standard library: as for the go command, the directories of
// GOROOT/src with Go files, on every platform (cmd excluded).
// stdtypes.IsStd reads it: a path without a dot in its first element is not
// always a standard library package (a main module "test" has packages
// test/a, test/b).
func writePaths(dir, release string) error {
	out, err := exec.Command("go", "env", "GOROOT").Output()
	if err != nil {
		return fmt.Errorf("go env GOROOT: %v", err)
	}
	src := filepath.Join(strings.TrimSpace(string(out)), "src")
	var paths []string
	err = filepath.WalkDir(src, func(path string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if d.IsDir() {
			// The go command ignores testdata and the directories whose
			// name starts with "." or "_".
			if n := d.Name(); path != src && (n == "testdata" || n == "cmd" && filepath.Dir(path) == src || strings.HasPrefix(n, ".") || strings.HasPrefix(n, "_")) {
				return filepath.SkipDir
			}
			return nil
		}
		if strings.HasSuffix(d.Name(), ".go") {
			rel, err := filepath.Rel(src, filepath.Dir(path))
			if err != nil {
				return err
			}
			if p := filepath.ToSlash(rel); len(paths) == 0 || paths[len(paths)-1] != p {
				paths = append(paths, p)
			}
		}
		return nil
	})
	if err != nil {
		return err
	}
	paths = slices.Compact(slices.Sorted(slices.Values(paths)))
	var b strings.Builder
	fmt.Fprintf(&b, `// Code generated by cmd/stdexport. DO NOT EDIT.

//go:build %s

package stdtypes

// stdPaths are the import paths of the standard library packages of this Go
// release (the directories of GOROOT/src with Go files, cmd excluded),
// sorted.
var stdPaths = []string{
`, release)
	for _, p := range paths {
		fmt.Fprintf(&b, "\t%q,\n", p)
	}
	b.WriteString("}\n")
	return os.WriteFile(filepath.Join(dir, prefix+"_data_packages.go"), []byte(b.String()), 0o644)
}

func write(dir, goos, goarch, release, nm string) error {
	cfg := &packages.Config{
		Mode: packages.NeedName | packages.NeedTypes | packages.NeedImports | packages.NeedDeps | packages.NeedFiles,
		// The VM calls the standard library natively: export the API of
		// the packages linked into a pure Go binary of the target.
		Env: append(os.Environ(), "GOOS="+goos, "GOARCH="+goarch, "CGO_ENABLED=0", "GOFLAGS=-mod=mod"),
	}
	pkgs, err := packages.Load(cfg, "std")
	if err != nil {
		return err
	}
	sort.Slice(pkgs, func(i, j int) bool { return pkgs[i].PkgPath < pkgs[j].PkgPath })
	var raw bytes.Buffer
	// Header: format, Go version (major.minor), platform.
	fmt.Fprintf(&raw, "govm-stdtypes 3\n%s\n%s/%s\n", gorelease.Release(runtime.Version()), goos, goarch)
	n := 0
	byPath := map[string]*packages.Package{}
	for _, p := range pkgs {
		byPath[p.PkgPath] = p
	}
	for _, path := range srcPkgs {
		p := byPath[path]
		if p == nil {
			return fmt.Errorf("no package %s", path)
		}
		for _, f := range p.GoFiles {
			b, err := os.ReadFile(f)
			if err != nil {
				return err
			}
			fmt.Fprintf(&raw, "!src %s/%s %d\n", path, filepath.Base(f), len(b))
			raw.Write(b)
		}
	}
	for _, p := range pkgs {
		if p.Types == nil || p.PkgPath == "unsafe" || strings.HasPrefix(p.PkgPath, "cmd/") {
			continue
		}
		if len(p.Errors) > 0 {
			return fmt.Errorf("%s: %v", p.PkgPath, p.Errors[0])
		}
		var b bytes.Buffer
		if err := gcexportdata.Write(&b, token.NewFileSet(), p.Types); err != nil {
			return fmt.Errorf("%s: %v", p.PkgPath, err)
		}
		fmt.Fprintf(&raw, "%s %d\n", p.PkgPath, b.Len())
		raw.Write(b.Bytes())
		n++
	}
	tasks, err := initTasks(nm, cfg.Env)
	if err != nil {
		return err
	}
	for _, p := range pkgs {
		if deps, ok := tasks[p.PkgPath]; ok {
			body := strings.Join(deps, " ")
			fmt.Fprintf(&raw, "!init %s %d\n%s", p.PkgPath, len(body), body)
		}
	}
	var z bytes.Buffer
	w, _ := gzip.NewWriterLevel(&z, gzip.BestCompression)
	w.Write(raw.Bytes())
	w.Close()
	gz := fmt.Sprintf("%s_std_%s_%s.gz", prefix, goos, goarch)
	name := filepath.Join(dir, gz)
	if err := os.WriteFile(name, z.Bytes(), 0o644); err != nil {
		return err
	}
	src := fmt.Sprintf(`// Code generated by cmd/stdexport. DO NOT EDIT.

//go:build %s

package stdtypes

import _ "embed"

//go:embed %s
var data []byte
`, release, gz)
	if err := os.WriteFile(filepath.Join(dir, fmt.Sprintf("%s_data_%s_%s.go", prefix, goos, goarch)), []byte(src), 0o644); err != nil {
		return err
	}
	fmt.Printf("%s/%s: %d packages, %d bytes (%d compressed)\n", goos, goarch, n, raw.Len(), z.Len())
	return nil
}

// initTasks returns the init graph of gc for pkgs: the packages that have an
// init task (the symbol "path..inittask" that the compiler writes when the
// package has init work or imports a package that has some), each with the
// packages of its imports that have one too (the R_INITORDER relocations
// of the task). The linker orders the init of a program over this graph
// (cmd/link/internal/ld/inittask.go): a package without a task, as
// unicode/utf8, is not in it, and the packages that import it do not wait
// for it. The VM orders the init of the interpreted packages the same way
// (vm/initorder.go). The graph is read from the object files of the
// packages with nm (the path of the go tool nm binary). It loads the
// packages again, only for their object files: the types of the export data
// written above are the ones of a load without them.
func initTasks(nm string, env []string) (map[string][]string, error) {
	pkgs, err := packages.Load(&packages.Config{Mode: packages.NeedName | packages.NeedFiles | packages.NeedExportFile, Env: env}, "std")
	if err != nil {
		return nil, err
	}
	tasks := map[string][]string{}
	for _, p := range pkgs {
		if p.PkgPath == "unsafe" || strings.HasPrefix(p.PkgPath, "cmd/") {
			continue
		}
		if p.ExportFile == "" {
			if len(p.GoFiles) == 0 {
				continue // only test files on this platform
			}
			return nil, fmt.Errorf("%s: no export file", p.PkgPath)
		}
		out, err := exec.Command(nm, p.ExportFile).Output()
		if err != nil {
			return nil, fmt.Errorf("nm %s: %v", p.PkgPath, err)
		}
		var deps []string
		defined := false
		for _, l := range strings.Split(string(out), "\n") {
			f := strings.Fields(l)
			if len(f) < 2 {
				continue
			}
			name, ok := strings.CutSuffix(f[len(f)-1], "..inittask")
			if !ok {
				continue
			}
			// The symbol names escape some bytes of the path as %xx
			// (objabi.PathToPrefix).
			path, err := url.PathUnescape(name)
			if err != nil {
				return nil, fmt.Errorf("%s: symbol %s: %v", p.PkgPath, f[len(f)-1], err)
			}
			switch f[len(f)-2] {
			case "D":
				if path != p.PkgPath {
					return nil, fmt.Errorf("%s: defines the init task of %s", p.PkgPath, path)
				}
				defined = true
			case "U":
				deps = append(deps, path)
			}
		}
		if defined {
			slices.Sort(deps)
			tasks[p.PkgPath] = slices.Compact(deps)
		} else if len(deps) > 0 {
			return nil, fmt.Errorf("%s: no init task, but refers to the one of %v", p.PkgPath, deps)
		}
	}
	// Every dependency is a package of the graph.
	for path, deps := range tasks {
		for _, d := range deps {
			if _, ok := tasks[d]; !ok {
				return nil, fmt.Errorf("%s: imports %s, which has no init task", path, d)
			}
		}
	}
	return tasks, nil
}
