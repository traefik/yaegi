// ---- shims ----

//go:embed shims
var shimFS embed.FS

//go:embed generics
var genericFS embed.FS

// genericGlue returns the hand-written hooks of the generic functions of
// pkgPath (generics/<pkgPath>/*.go.in, one file), or nil.
func genericGlue(pkgPath string) []byte {
	b, err := genericFS.ReadFile(path.Join("generics", pkgPath, "generic.go.in"))
	if err != nil {
		return nil
	}
	return b
}

// shimFiles returns the hand-written replacement of a package that cannot be
// copied out of the standard library (linkname into the runtime), or nil.
func shimFiles(pkgPath string) map[string][]byte {
	dir := path.Join("shims", pkgPath)
	ents, err := fs.ReadDir(shimFS, dir)
	if err != nil {
		return nil
	}
	out := map[string][]byte{}
	for _, e := range ents {
		if e.IsDir() || !strings.HasSuffix(e.Name(), ".go") {
			continue
		}
		b, err := shimFS.ReadFile(path.Join(dir, e.Name()))
		if err == nil {
			out[e.Name()] = b
		}
	}
	if len(out) == 0 {
		return nil
	}
	return out
}

// ---- native symbol tables of non-std targets ----

func (g *gen) genNative() error {
	var all []string
	for _, pi := range g.sorted() {
		if !pi.target || isStd(pi.p) {
			continue
		}
		dir := filepath.Join(g.natDir, filepath.FromSlash(pi.p.PkgPath))
		if err := os.MkdirAll(dir, 0o755); err != nil {
			return err
		}
		gl := &glue{g: g, pi: pi, pkg: pi.p.Types, inPath: g.natPath + "/" + pi.p.PkgPath, imports: map[string]string{},
			names: map[string]bool{vmName: true, "aotreflect": true}, native: true}
		gl.selfQ = gl.importName(pi.p.PkgPath, pi.p.Name)
		// the native table imports the original package, not its AOT copy
		gl.imports = map[string]string{pi.p.PkgPath: gl.selfQ}
		var body bytes.Buffer
		fmt.Fprintf(&body, "func init() {\n\t%s.RegisterNativePackage(&%s.Package{\n\t\tPath: %q,\n", vmName, vmName, pi.p.PkgPath)
		scope := pi.p.Types.Scope()
		names := scope.Names()
		sort.Strings(names)
		var funcs, typs, vars []string
		for _, n := range names {
			obj := scope.Lookup(n)
			if !obj.Exported() {
				continue
			}
			q := gl.selfQ + "." + n
			switch o := obj.(type) {
			case *types.Func:
				if o.Type().(*types.Signature).TypeParams() == nil {
					funcs = append(funcs, fmt.Sprintf("\t\t\t%q: aotreflect.ValueOf(%s),\n", n, q))
				}
			case *types.TypeName:
				if nt, ok := o.Type().(*types.Named); ok && nt.TypeParams() != nil {
					continue
				}
				if al, ok := o.Type().(*types.Alias); ok && al.TypeParams() != nil {
					continue
				}
				if it, ok := o.Type().Underlying().(*types.Interface); ok && !it.IsMethodSet() {
					continue // constraint interface
				}
				typs = append(typs, fmt.Sprintf("\t\t\t%q: aotreflect.TypeFor[%s](),\n", n, q))
			case *types.Var:
				vars = append(vars, fmt.Sprintf("\t\t\t%q: aotreflect.ValueOf(&%s),\n", n, q))
			}
		}
		for _, x := range []struct {
			field, typ string
			e          []string
		}{{"Funcs", "Value", funcs}, {"Types", "Type", typs}, {"Vars", "Value", vars}} {
			fmt.Fprintf(&body, "\t\t%s: map[string]aotreflect.%s{\n%s\t\t},\n", x.field, x.typ, strings.Join(x.e, ""))
		}
		body.WriteString("\t})\n}\n")
		var b bytes.Buffer
		fmt.Fprintf(&b, "// Code generated by aotgen -native. DO NOT EDIT.\n\n// Package %s registers the native symbol table of %s for the VM's\n// native mode (vm.ModeNative).\npackage %s\n\nimport (\n\taotreflect \"reflect\"\n\t%s %q\n\t%s %q\n)\n\n",
			pi.p.Name, pi.p.PkgPath, pi.p.Name, vmName, vmPath, gl.selfQ, pi.p.PkgPath)
		b.Write(body.Bytes())
		src, err := format.Source(b.Bytes())
		if err != nil {
			return fmt.Errorf("native table of %s: %w", pi.p.PkgPath, err)
		}
		if err := os.WriteFile(filepath.Join(dir, "zz_natsyms.go"), src, 0o644); err != nil {
			return err
		}
		all = append(all, g.natPath+"/"+pi.p.PkgPath)
	}
	var b bytes.Buffer
	b.WriteString("// Code generated by aotgen -native. DO NOT EDIT.\n\n// Package all registers every native symbol table generated by aotgen.\npackage all\n\n")
	if len(all) > 0 {
		b.WriteString("import (\n")
		for _, p := range all {
			fmt.Fprintf(&b, "\t_ %q\n", p)
		}
		b.WriteString(")\n")
	}
	dir := filepath.Join(g.natDir, "all")
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return err
	}
	src, err := format.Source(b.Bytes())
	if err != nil {
		return err
	}
	return os.WriteFile(filepath.Join(dir, "all.go"), src, 0o644)
}

// ---- licenses ----

func findLicense(dir string) string {
	for d := dir; ; d = filepath.Dir(d) {
		for _, n := range []string{"LICENSE", "LICENSE.md", "LICENSE.txt", "COPYING", "LICENCE"} {
			if _, err := os.Stat(filepath.Join(d, n)); err == nil {
				return filepath.Join(d, n)
			}
		}
		if filepath.Dir(d) == d {
			return ""
		}
		if _, err := os.Stat(filepath.Join(d, "go.mod")); err == nil {
			return ""
		}
	}
}

func (g *gen) licenses() error {
	// The GOROOT of the go command that loads the packages (runtime.GOROOT
	// is the one of the aotgen build, which may be another machine).
	out, err := exec.Command("go", "env", "GOROOT").Output()
	if err != nil {
		return fmt.Errorf("go env GOROOT: %w", err)
	}
	goroot := strings.TrimSpace(string(out))
	licDir := filepath.Join(g.root, "LICENSES")
	if err := os.MkdirAll(licDir, 0o755); err != nil {
		return err
	}
	for _, pi := range g.sorted() {
		if pi.kind == kNative {
			continue
		}
		var src string
		if pi.p.Module == nil {
			src = filepath.Join(goroot, "LICENSE")
			if _, err := os.Stat(src); err != nil {
				// Some distributions (nix) ship GOROOT without LICENSE.
				src = filepath.Join(licDir, "Go-BSD-3-Clause.txt")
			}
		} else {
			src = findLicense(pi.p.Module.Dir)
		}
		if src == "" {
			pi.blockers = append(pi.blockers, "no license file found")
			continue
		}
		b, err := os.ReadFile(src)
		if err != nil {
			return err
		}
		if err := os.WriteFile(filepath.Join(pi.dir, "LICENSE"), b, 0o644); err != nil {
			return err
		}
		if pi.p.Module == nil {
			pi.license = "Go (BSD-3-Clause), LICENSES/Go-BSD-3-Clause.txt"
			continue
		}
		name := sanitizeFile(pi.p.Module.Path) + ".txt"
		pi.license = pi.p.Module.Path + "@" + pi.p.Module.Version + ", LICENSES/" + name
		if err := os.WriteFile(filepath.Join(licDir, name), b, 0o644); err != nil {
			return err
		}
	}
	return nil
}

func sanitizeFile(s string) string {
	return strings.NewReplacer("/", "_", "@", "_").Replace(s)
}

// ---- build ----

func (g *gen) build() {
	var wg sync.WaitGroup
	sem := make(chan struct{}, runtime.NumCPU())
	for _, pi := range g.sorted() {
		if pi.kind == kNative {
			continue
		}
		wg.Add(1)
		go func() {
			defer wg.Done()
			sem <- struct{}{}
			defer func() { <-sem }()
			cmd := exec.Command("go", "build", "-o", os.DevNull, pi.aotPath)
			cmd.Dir = g.root
			out, err := cmd.CombinedOutput()
			if err != nil {
				lines := strings.Split(strings.TrimSpace(string(out)), "\n")
				if len(lines) > 12 {
					lines = append(lines[:12], fmt.Sprintf("... (%d more lines)", len(lines)-12))
				}
				pi.buildErr = strings.Join(lines, "\n")
				return
			}
			pi.built = true
		}()
	}
	wg.Wait()
}

// quarantine moves the files of the packages that do not build to
// <o>/_failed/ (ignored by ./... patterns, kept for inspection) and
// regenerates <o>/all without them.
func (g *gen) quarantine() error {
	for _, pi := range g.sorted() {
		if pi.kind == kNative || pi.built {
			continue
		}
		dst := filepath.Join(g.outDir, "_failed", filepath.FromSlash(mapDir(pi.p.PkgPath)))
		if err := os.MkdirAll(dst, 0o755); err != nil {
			return err
		}
		ents, err := os.ReadDir(pi.dir)
		if err != nil {
			return err
		}
		for _, e := range ents {
			if e.IsDir() {
				continue
			}
			if err := os.Rename(filepath.Join(pi.dir, e.Name()), filepath.Join(dst, e.Name())); err != nil {
				return err
			}
		}
		pi.notes = append(pi.notes, "does not build: moved to "+strings.TrimPrefix(filepath.ToSlash(strings.TrimPrefix(filepath.Join(g.outDir, "_failed", mapDir(pi.p.PkgPath)), g.root)), "/"))
	}
	if err := g.writeAll(); err != nil {
		return err
	}
	return g.writeAllConstrained()
}

// ---- report ----

func (g *gen) reportText() string {
	var b strings.Builder
	b.WriteString("aotgen report\n=============\n\ntargets: " + strings.Join(g.targets, " ") + "\n\n")
	b.WriteString(g.summary())
	for _, pi := range g.sorted() {
		if pi.kind == kNative {
			continue
		}
		fmt.Fprintf(&b, "\n== %s [%s: %s] -> %s\n", pi.p.PkgPath, pi.kind, pi.why, pi.aotPath)
		if pi.license != "" {
			fmt.Fprintf(&b, "license: %s\n", pi.license)
		}
		status := "not built"
		switch {
		case pi.built:
			status = "ok"
		case pi.buildErr != "":
			status = "FAIL\n    " + strings.ReplaceAll(pi.buildErr, "\n", "\n    ")
		}
		fmt.Fprintf(&b, "build: %s\n", status)
		if len(pi.used) > 0 {
			keys := make([]string, 0, len(pi.used))
			for k := range pi.used {
				keys = append(keys, k)
			}
			sort.Strings(keys)
			fmt.Fprintf(&b, "reflect API used (%d members):\n", len(keys))
			var line strings.Builder
			for _, k := range keys {
				item := fmt.Sprintf("%s x%d", k, pi.used[k])
				if line.Len()+len(item) > 100 {
					b.WriteString("    " + line.String() + "\n")
					line.Reset()
				}
				if line.Len() > 0 {
					line.WriteString(", ")
				}
				line.WriteString(item)
			}
			if line.Len() > 0 {
				b.WriteString("    " + line.String() + "\n")
			}
			fmt.Fprintf(&b, "missing from the twin: %s\n", listOr(pi.missing, "none"))
			fmt.Fprintf(&b, "partial in the twin: %s\n", listOr(pi.partial, "none"))
		}
		if pi.kind == kConvert {
			fmt.Fprintf(&b, "rewrites: %d interface assertions, %d type switches, %d interface comparisons, %d interface tag switches, %d composite unboxes, %d vet fixes, %d linknames removed, %d assertions left native\n",
				pi.asserts, pi.switches, pi.eqs, pi.tagSwitches, pi.unboxes, pi.vetFixes, pi.linknames, pi.skippedAsserts)
			fmt.Fprintf(&b, "glue: %d hooks, %d wrappers; no hook (generic reflect.Call path): %s\n", pi.hooks, pi.wrappers, listOr(pi.noHook, "none"))
			if pi.typeCaches > 0 {
				fmt.Fprintf(&b, "type caches: %d package-level sync.Map made vm.TypeCache\n", pi.typeCaches)
			}
			if pi.typeMaps > 0 {
				fmt.Fprintf(&b, "type maps: %d package-level maps indexed by reflect.Type made vm.TypeMap\n", pi.typeMaps)
			}
			if pi.nestGuards > 0 {
				fmt.Fprintf(&b, "recursion guards: %d recursive calls counted by vm.NestAOT\n", pi.nestGuards)
			}
			if pi.ptrKeys > 0 {
				fmt.Fprintf(&b, "pointer keys: %d cycle check keys made vm.PtrKey\n", pi.ptrKeys)
			}
			if pi.jsonNoUnboxes+pi.jsonAddrCopies > 0 {
				fmt.Fprintf(&b, "cycle check: %d Unbox made vm.NoUnbox, %d copies made vm.AddrCopy\n", pi.jsonNoUnboxes, pi.jsonAddrCopies)
			}
		}
		if pi.exits > 0 {
			fmt.Fprintf(&b, "process exits: %d uses of os.Exit, log.Fatal and os.Args made vm.AOTExit, AOTFatal, AOTArgs\n", pi.exits)
		}
		if pi.httpDefaults > 0 {
			fmt.Fprintf(&b, "default mux: %d uses of http.Handle, http.DefaultServeMux and the nil-handler functions made vm.AOTHandle, AOTDefaultServeMux...\n", pi.httpDefaults)
		}
		if pi.unsafeUses > 0 || pi.goStmts > 0 {
			fmt.Fprintf(&b, "risks: %d uses of unsafe, %d go statements\n", pi.unsafeUses, pi.goStmts)
		}
		for _, x := range pi.blockers {
			fmt.Fprintf(&b, "BLOCKER: %s\n", x)
		}
		for _, x := range pi.notes {
			fmt.Fprintf(&b, "note: %s\n", x)
		}
	}
	return b.String()
}

func listOr(xs []string, none string) string {
	if len(xs) == 0 {
		return none
	}
	return strings.Join(xs, ", ")
}

func (g *gen) summary() string {
	var b strings.Builder
	b.WriteString(fmt.Sprintf("%-50s %-7s %-6s %5s %7s %s\n", "package", "kind", "build", "refl", "missing", "blockers"))
	for _, pi := range g.sorted() {
		if pi.kind == kNative {
			continue
		}
		st := "-"
		switch {
		case pi.built:
			st = "ok"
		case pi.buildErr != "":
			st = "FAIL"
		}
		fmt.Fprintf(&b, "%-50s %-7s %-6s %5d %7d %d\n", pi.p.PkgPath, pi.kind, st, len(pi.used), len(pi.missing), len(pi.blockers))
	}
	return b.String()
}
