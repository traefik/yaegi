package main

// The AOT copies of each Go release of the window of yaegi v2
// (gorelease.Window) are side by side: aot/go1_26/..., aot/go1_27/...
// A run of aotgen writes the tree of the release of its toolchain, and adds
// the build constraint of that release to each Go file of the tree
// (addRelease), so that the other release builds none of it. aot/all, the
// package that hosts import, has one file per release that imports the
// all package of its tree, and the guard of the window (writeTop).

import (
	"bytes"
	"fmt"
	"go/build/constraint"
	"io/fs"
	"os"
	"os/exec"
	"path/filepath"
	"runtime"
	"strings"

	"github.com/traefik/yaegi/v2/internal/gorelease"
	"github.com/traefik/yaegi/v2/internal/gosources"
)

// addRelease adds the build constraint expr (the release of the tree:
// "go1.27 && !go1.28") to every Go file under dir, except the quarantined
// ones (_failed). A file that has a constraint gets both; a file that has
// it already is left as it is.
func addRelease(dir, expr string) error {
	return filepath.WalkDir(dir, func(path string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if d.IsDir() {
			if d.Name() == "_failed" {
				return filepath.SkipDir
			}
			return nil
		}
		if !strings.HasSuffix(path, ".go") {
			return nil
		}
		src, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		out, err := withRelease(src, expr)
		if err != nil {
			return fmt.Errorf("%s: %v", path, err)
		}
		if bytes.Equal(out, src) {
			return nil
		}
		return os.WriteFile(path, out, 0o644)
	})
}

// withRelease returns src with the build constraint expr added to its
// //go:build line, or a new line when it has none.
func withRelease(src []byte, expr string) ([]byte, error) {
	lines := strings.SplitAfter(string(src), "\n")
	for i, l := range lines {
		t := strings.TrimSpace(l)
		if strings.HasPrefix(t, "package ") {
			break
		}
		old, ok := strings.CutPrefix(t, "//go:build ")
		if !ok {
			continue
		}
		if strings.Contains(old, expr) {
			return src, nil
		}
		x, err := constraint.Parse("//go:build " + old)
		if err != nil {
			return nil, err
		}
		both := "(" + x.String() + ") && " + expr
		if _, ok := x.(*constraint.OrExpr); !ok {
			both = x.String() + " && " + expr
		}
		lines[i] = "//go:build " + both + "\n"
		return []byte(strings.Join(lines, "")), nil
	}
	return append([]byte("//go:build "+expr+"\n\n"), src...), nil
}

// writeTop writes the files of <top>/all for the release of the toolchain:
// <top>/all/go1_NN.go, built by that release only, imports the all package
// of the tree of the release; release_guard.go stops the build on a release
// outside the window.
func writeTop(topDir, topPath, prefix, expr string) error {
	dir := filepath.Join(topDir, "all")
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return err
	}
	// The files of the releases outside the window go.
	old, _ := filepath.Glob(filepath.Join(dir, "go1_*.go"))
	for _, f := range old {
		if gorelease.OutsideWindow(f) {
			os.Remove(f)
		}
	}
	src := fmt.Sprintf(`// Code generated by aotgen. DO NOT EDIT.

//go:build %s

// Package all registers every package generated by aotgen for the Go
// release of the build (import it for its side effects): the AOT copies of
// each release of the window of yaegi v2 are in a tree of their own.
package all

import _ %q
`, expr, topPath+"/"+prefix+"/all")
	if err := os.WriteFile(filepath.Join(dir, prefix+".go"), []byte(src), 0o644); err != nil {
		return err
	}
	guard := gorelease.Guard("aotgen", topPath+"/all", "sh scripts/aotgen.sh, with the toolchain of each release")
	return os.WriteFile(filepath.Join(dir, "release_guard.go"), guard, 0o644)
}

// cleanTrees removes the trees of the releases outside the window.
func cleanTrees(topDir string) {
	trees, _ := filepath.Glob(filepath.Join(topDir, "go1_*"))
	for _, t := range trees {
		if gorelease.OutsideWindow(t) {
			os.RemoveAll(t)
		}
	}
}

// recordGoSources writes the entry of the Go version of aotgen in
// <top>/all/gosources.txt (internal/gosources): the hash of the GOROOT
// sources of each standard package copied in outDir. The entries of the
// older patch releases of the release go (the copies are now made with
// this one); the newer ones stay (cmd/aotgosrc adds them).
func recordGoSources(topDir, outDir string) error {
	pkgs, err := gosources.StdCopies(outDir)
	if err != nil {
		return err
	}
	out, err := exec.Command("go", "env", "GOROOT").Output()
	if err != nil {
		return fmt.Errorf("go env GOROOT: %v", err)
	}
	return gosources.Record(filepath.Join(topDir, "all", "gosources.txt"), runtime.Version(), strings.TrimSpace(string(out)), pkgs, true)
}
