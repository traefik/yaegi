package main

// The native table of golang.org/x/sys/unix (stdsyms/xsys_unix_*.go).
//
// Plugins import golang.org/x/sys/unix through gRPC, zap, wazero, the
// OpenTelemetry SDK... Run from source, its system calls go through
// assembly (Syscall6 on linux) or through the C library (darwin, openbsd),
// which the VM cannot run. The host links its own copy of the package (the
// version of its go.mod): the VM can call it instead (vm/xsys.go). Its API
// is different on each platform, as the one of syscall: one file per
// platform, which its name selects (_GOOS_GOARCH.go).
//
// The table has the exported functions, types and variables. Constants are
// not in it: the VM takes them from the plugin's source, as the compiler
// does.

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/build"
	"go/format"
	"go/importer"
	"go/parser"
	"go/token"
	"go/types"
	"os"
	"os/exec"
	"path/filepath"
	"sort"
	"strings"
)

// xsysUnix is the import path of the package.
const xsysUnix = "golang.org/x/sys/unix"

// xsysVersion returns the version of golang.org/x/sys in yaegi v2's go.mod.
func xsysVersion() (string, error) {
	cmd := exec.Command("go", "list", "-m", "-f", "{{.Version}}", "golang.org/x/sys")
	cmd.Stderr = os.Stderr
	out, err := cmd.Output()
	if err != nil {
		return "", fmt.Errorf("version of golang.org/x/sys: %v", err)
	}
	return strings.TrimSpace(string(out)), nil
}

// writeXSys writes the table of golang.org/x/sys/unix for each unix
// platform of platforms into dir. The caller sets build.Default back.
func writeXSys(dir string, saved build.Context, platforms []string) (int, error) {
	old, _ := filepath.Glob(filepath.Join(dir, "xsys_unix_*.go"))
	for _, f := range old {
		os.Remove(f)
	}
	version, err := xsysVersion()
	if err != nil {
		return 0, err
	}
	// go/build does not find the packages of modules with the tool tags of
	// another platform: the directory comes from go list, and the files
	// for the platform from go/build.
	cmd := exec.Command("go", "list", "-f", "{{.Dir}}", xsysUnix)
	cmd.Stderr = os.Stderr
	out, err := cmd.Output()
	if err != nil {
		return 0, fmt.Errorf("directory of %s: %v", xsysUnix, err)
	}
	srcDir := strings.TrimSpace(string(out))
	n := 0
	for _, pl := range platforms {
		if strings.HasPrefix(pl, "windows/") {
			continue // no golang.org/x/sys/unix there
		}
		if err := setPlatform(&build.Default, saved, pl); err != nil {
			return n, err
		}
		pkg, err := checkDir(srcDir, xsysUnix)
		if err != nil {
			return n, fmt.Errorf("%s for %s: %v", xsysUnix, pl, err)
		}
		src, err := xsysFile(pkg, version, pl)
		if err != nil {
			return n, fmt.Errorf("%s for %s: %v", xsysUnix, pl, err)
		}
		name := filepath.Join(dir, "xsys_unix_"+build.Default.GOOS+"_"+build.Default.GOARCH+".go")
		if err := os.WriteFile(name, src, 0o644); err != nil {
			return n, err
		}
		n++
	}
	return n, nil
}

// checkDir type checks the package path in dir for the platform of
// build.Default. Its imports must be standard library packages.
func checkDir(dir, path string) (*types.Package, error) {
	bp, err := build.Default.ImportDir(dir, 0)
	if err != nil {
		return nil, err
	}
	fset := token.NewFileSet()
	var files []*ast.File
	for _, name := range bp.GoFiles {
		f, err := parser.ParseFile(fset, filepath.Join(dir, name), nil, 0)
		if err != nil {
			return nil, err
		}
		files = append(files, f)
	}
	conf := types.Config{
		Importer: importer.ForCompiler(fset, "source", nil),
		Sizes:    types.SizesFor("gc", build.Default.GOARCH),
	}
	return conf.Check(path, fset, files, nil)
}

// xsysFile returns the file of the table of pkg (golang.org/x/sys/unix of
// the platform pl), made from version of the module.
func xsysFile(pkg *types.Package, version, pl string) ([]byte, error) {
	var funcs, typs, vars []string
	sc := pkg.Scope()
	for _, name := range sc.Names() {
		o := sc.Lookup(name)
		if !o.Exported() {
			continue
		}
		switch o := o.(type) {
		case *types.Func:
			if o.Type().(*types.Signature).TypeParams().Len() > 0 {
				continue // generic: no native instance
			}
			funcs = append(funcs, name)
		case *types.TypeName:
			if t, ok := o.Type().(*types.Named); ok && t.TypeParams().Len() > 0 {
				continue
			}
			if it, ok := o.Type().Underlying().(*types.Interface); ok && !it.IsMethodSet() {
				continue // a constraint
			}
			typs = append(typs, name)
		case *types.Var:
			vars = append(vars, name)
		}
	}
	sort.Strings(funcs)
	sort.Strings(typs)
	sort.Strings(vars)
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by cmd/stdsyms for %s (%s). DO NOT EDIT.\n\n", xsysUnix, pl)
	b.WriteString("package stdsyms\n\nimport (\n\t\"reflect\"\n\n\t\"golang.org/x/sys/unix\"\n)\n\n")
	b.WriteString("func init() {\n\tXSysUnix = &NativeTable{\n")
	fmt.Fprintf(&b, "\t\tVersion: %q,\n", version)
	b.WriteString("\t\tFuncs: map[string]reflect.Value{\n")
	for _, name := range funcs {
		fmt.Fprintf(&b, "\t\t\t%q: reflect.ValueOf(unix.%s),\n", name, name)
	}
	b.WriteString("\t\t},\n\t\tTypes: map[string]reflect.Type{\n")
	for _, name := range typs {
		fmt.Fprintf(&b, "\t\t\t%q: reflect.TypeFor[unix.%s](),\n", name, name)
	}
	b.WriteString("\t\t},\n\t\tVars: map[string]reflect.Value{\n")
	for _, name := range vars {
		fmt.Fprintf(&b, "\t\t\t%q: reflect.ValueOf(&unix.%s),\n", name, name)
	}
	b.WriteString("\t\t},\n\t}\n}\n")
	return format.Source(b.Bytes())
}
