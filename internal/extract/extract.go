// Package extract writes the native symbol table of a package: a Go file
// that adds to a map, for every exported symbol of the package, a
// reflect.Value of it, and wrapper types for its interfaces. cmd/stdsyms
// uses it to generate package stdsyms. It is yaegi v2's own copy of yaegi's
// extractor, so the generators of yaegi v2 do not depend on yaegi.
package extract

import (
	"bytes"
	"fmt"
	"go/constant"
	"go/format"
	"go/importer"
	"go/token"
	"go/types"
	"math/big"
	"path"
	"strings"
	"text/template"
)

const model = `// Code generated by cmd/stdsyms for {{.ImportPath}}. DO NOT EDIT.

{{if .Build}}//go:build {{.Build}}{{end}}

package {{.Dest}}

import (
{{- range $key, $value := .Imports }}
	{{- if $value}}
	"{{$key}}"
	{{- end}}
{{- end}}
{{- if or .Val .Typ }}
	"{{.ImportPath}}"
{{- end}}
	"reflect"
)

func init() {
	{{.Table}}["{{.PkgName}}"] = map[string]reflect.Value{
		{{- if .Val}}
		// function, constant and variable definitions
		{{range $key, $value := .Val -}}
			{{- if $value.Addr -}}
				"{{$key}}": reflect.ValueOf(&{{$value.Name}}).Elem(),
			{{else -}}
				"{{$key}}": reflect.ValueOf({{$value.Name}}),
			{{end -}}
		{{end}}

		{{- end}}
		{{- if .Typ}}
		// type definitions
		{{range $key, $value := .Typ -}}
			"{{$key}}": reflect.ValueOf((*{{$value}})(nil)),
		{{end}}

		{{- end}}
		{{- if .Wrap}}
		// interface wrapper definitions
		{{range $key, $value := .Wrap -}}
			"_{{$key}}": reflect.ValueOf((*{{$value.Name}})(nil)),
		{{end}}
		{{- end}}
	}
}
{{range $key, $value := .Wrap -}}
	// {{$value.Name}} is an interface wrapper for {{$key}} type
	type {{$value.Name}} struct {
		IValue interface{}
		{{range $m := $value.Method -}}
		W{{$m.Name}} func{{$m.Param}} {{$m.Result}}
		{{end}}
	}
	{{range $m := $value.Method -}}
		func (W {{$value.Name}}) {{$m.Name}}{{$m.Param}} {{$m.Result}} {
			{{- if eq $m.Name "String"}}
			if W.WString == nil {
				return ""
			}
			{{end -}}
			{{$m.Ret}} W.W{{$m.Name}}{{$m.Arg}}
		}
	{{end}}
{{end}}
`

var tmpl = template.Must(template.New("extract").Parse(model))

// Config says how to write the file of a package.
type Config struct {
	Dest  string // the name of the package of the file: "stdsyms"
	Table string // the map that gets the symbols: "Symbols" or "Unrestricted"
	Build string // the build constraint of the file ("go1.26 && !windows"); none if empty
}

// val is the expression and the kind of a symbol.
type val struct {
	Name string // "package.name"
	Addr bool   // true if the symbol is a variable
}

// method is a method of an interface wrapper.
type method struct {
	Name, Param, Result, Arg, Ret string
}

// wrap is the wrapper type of an interface.
type wrap struct {
	Name   string
	Method []method
}

// restricted are the symbols that the destination package replaces with its
// own version: "osExit" is used instead of os.Exit (stdsyms/restricted.go).
var restricted = map[string]bool{
	"osExit":        true,
	"osFindProcess": true,
	"logFatal":      true,
	"logFatalf":     true,
	"logFatalln":    true,
	"logLogger":     true,
	"logNew":        true,
}

// Extract type checks the package of importPath from its sources (with
// go/build.Default: change its GOOS and GOARCH to extract for another
// platform) and returns its file.
func Extract(importPath string, c Config) ([]byte, error) {
	pkg, err := importer.ForCompiler(token.NewFileSet(), "source", nil).Import(importPath)
	if err != nil {
		return nil, err
	}
	return Generate(importPath, pkg, c)
}

// Generate returns the file of package p, whose import path is importPath.
func Generate(importPath string, p *types.Package, c Config) ([]byte, error) {
	prefix := "_" + importPath + "_"
	prefix = strings.NewReplacer("/", "_", "-", "_", ".", "_", "~", "_").Replace(prefix)

	typ := map[string]string{}
	vals := map[string]val{}
	wraps := map[string]wrap{}
	imports := map[string]bool{}
	sc := p.Scope()

	for _, pkg := range p.Imports() {
		imports[pkg.Path()] = false
	}
	qualify := func(pkg *types.Package) string {
		if pkg.Path() != importPath {
			imports[pkg.Path()] = true
		}
		return pkg.Name()
	}

	for _, name := range sc.Names() {
		o := sc.Lookup(name)
		if !o.Exported() {
			continue
		}

		pname := p.Name() + "." + name
		if rname := p.Name() + name; restricted[rname] {
			// A restricted symbol: the destination package has its own.
			pname = rname
		}

		switch o := o.(type) {
		case *types.Const:
			if b, ok := o.Type().(*types.Basic); ok && (b.Info()&types.IsUntyped) != 0 {
				// Convert an untyped constant to the right type to avoid overflow.
				vals[name] = val{fixConst(pname, o.Val(), imports), false}
			} else {
				vals[name] = val{pname, false}
			}
		case *types.Func:
			// Skip generic functions and methods.
			if s := o.Type().(*types.Signature); s.TypeParams().Len() > 0 || s.RecvTypeParams().Len() > 0 {
				continue
			}
			vals[name] = val{pname, false}
		case *types.Var:
			vals[name] = val{pname, true}
		case *types.TypeName:
			// Skip generic types.
			if t, ok := o.Type().(*types.Named); ok && t.TypeParams().Len() > 0 {
				continue
			}
			typ[name] = pname
			t, ok := o.Type().Underlying().(*types.Interface)
			if !ok {
				continue
			}
			if t.NumMethods() == 0 && t.NumEmbeddeds() != 0 {
				// Skip the interfaces that are only constraints of generics.
				delete(typ, name)
				continue
			}
			if wrapperUsesInternal(t) {
				continue
			}
			wraps[name] = wrap{prefix + name, wrapMethods(t, qualify)}
		}
	}

	// This check is defensive: today only wrapMethods calls qualify, and the
	// wrappers that name an internal package are skipped above, so no test
	// can reach it. It stays so that a later change that names other types
	// in the file (and so imports their package) fails here, not in the
	// build of package stdsyms.
	for p, used := range imports {
		if used && isInternal(p) {
			// Package stdsyms may not import it: do not hide such a use.
			return nil, fmt.Errorf("%s: the table uses the internal package %s", importPath, p)
		}
	}

	var b bytes.Buffer
	err := tmpl.Execute(&b, map[string]any{
		"Dest":       c.Dest,
		"Table":      c.Table,
		"Build":      c.Build,
		"Imports":    imports,
		"ImportPath": importPath,
		"PkgName":    path.Join(importPath, p.Name()),
		"Val":        vals,
		"Typ":        typ,
		"Wrap":       wraps,
	})
	if err != nil {
		return nil, fmt.Errorf("template error: %w", err)
	}
	source, err := format.Source(b.Bytes())
	if err != nil {
		return nil, fmt.Errorf("failed to format source: %w: %s", err, b.Bytes())
	}
	return source, nil
}

// wrapMethods returns the methods of the wrapper of interface t.
func wrapMethods(t *types.Interface, qualify types.Qualifier) []method {
	var methods []method
	for i := 0; i < t.NumMethods(); i++ {
		f := t.Method(i)
		if !f.Exported() {
			continue
		}

		sign := f.Type().(*types.Signature)
		args := make([]string, sign.Params().Len())
		params := make([]string, len(args))
		for j := range args {
			v := sign.Params().At(j)
			if args[j] = v.Name(); args[j] == "" {
				args[j] = fmt.Sprintf("a%d", j)
			}
			if sign.Variadic() && j == len(args)-1 {
				// The variadic parameter: "[]T" becomes "...T".
				at := types.TypeString(v.Type(), qualify)[2:]
				params[j] = args[j] + " ..." + at
				args[j] += "..."
			} else {
				params[j] = args[j] + " " + types.TypeString(v.Type(), qualify)
			}
		}
		arg := "(" + strings.Join(args, ", ") + ")"
		param := "(" + strings.Join(params, ", ") + ")"

		results := make([]string, sign.Results().Len())
		for j := range results {
			v := sign.Results().At(j)
			results[j] = v.Name() + " " + types.TypeString(v.Type(), qualify)
		}
		result := "(" + strings.Join(results, ", ") + ")"

		ret := ""
		if sign.Results().Len() > 0 {
			ret = "return"
		}

		methods = append(methods, method{f.Name(), param, result, arg, ret})
	}
	return methods
}

// wrapperUsesInternal reports whether the wrapper of interface t would name
// a type of an internal package.
//
// Package stdsyms may not import an internal package of the standard
// library. Since Go 1.27 (json v2 is on by default), encoding/json and
// encoding/json/v2 export Options, an interface whose only method is
// JSONOptions(internal.NotForPublicUse): its wrapper would import
// encoding/json/internal, and the package would not compile. Such an
// interface cannot be implemented outside the standard library, so an
// interpreted type never needs the wrapper. The type itself stays in the
// table.
func wrapperUsesInternal(t *types.Interface) bool {
	found := false
	_ = wrapMethods(t, func(pkg *types.Package) string {
		if isInternal(pkg.Path()) {
			found = true
		}
		return pkg.Name()
	})
	return found
}

// isInternal reports whether the import path p has an "internal" element.
func isInternal(p string) bool {
	for _, e := range strings.Split(p, "/") {
		if e == "internal" {
			return true
		}
	}
	return false
}

// fixConst returns the expression of an untyped constant: a
// constant.Value made from its literal, so that a large value does not
// overflow the default type of the constant.
func fixConst(name string, v constant.Value, imports map[string]bool) string {
	var (
		tok string
		str string
	)
	switch v.Kind() {
	case constant.String:
		tok = "STRING"
		str = v.ExactString()
	case constant.Int:
		tok = "INT"
		str = v.ExactString()
	case constant.Float:
		f, ok := constant.Val(v).(*big.Float) // else a *big.Rat
		if !ok {
			f = new(big.Float).SetRat(constant.Val(v).(*big.Rat))
		}
		tok = "FLOAT"
		str = f.Text('g', int(f.Prec()))
	default:
		// A complex constant keeps its name, as in yaegi.
		return name
	}

	imports["go/constant"] = true
	imports["go/token"] = true

	return fmt.Sprintf("constant.MakeFromLiteral(%q, token.%s, 0)", str, tok)
}
