// Package progen writes random Go programs for differential tests: the same
// seed gives the same program, a valid one that exits with status 0 and
// prints the same output at each run. cmd/runtests runs them with go and
// with yaegi v2 and compares the outputs (TestGeneratedPrograms).
//
// A program has global variables of each basic type, and functions of
// random statements over them: assignments of random expressions (the
// arithmetic of each integer width with its wrapping, shifts, division and
// remainder, conversions between the types, float64 arithmetic, string
// operations, comparisons), if, for, switch, closures, slices and maps.
// Each function runs under a recover that prints the panic (an integer
// division by zero, an index out of range, a negative shift count are
// expected), then the program prints its variables. The operations that can
// panic are in function calls (div, rem, shl, sub, set) when an expression
// can hold more than one: the spec fixes the order of calls, not the order
// of the other operations, and gc and the VM may panic on a different one.
//
// The expressions are never constant (a constant expression that overflows
// does not compile), floats are never converted to integers (an out of range
// value gives a result that depends on the platform in Go), each float
// operation is rounded by a conversion (gc may fuse x*y+z into one FMA
// instruction, which the spec allows: the result then depends on the
// platform), and maps are printed by fmt, which sorts them.
package progen

import (
	"fmt"
	"math/rand/v2"
	"strings"
)

// The types of the variables of a program.
var intTypes = []string{"int", "int8", "int16", "int32", "int64", "uint", "uint8", "uint16", "uint32", "uint64"}

var allTypes = append(append([]string{}, intTypes...), "float64", "bool", "string")

// gen writes one program.
type gen struct {
	r     *rand.Rand
	b     strings.Builder
	depth int
	vars  map[string][]string // type -> names of the global variables
}

// Generate returns the source of the program of seed.
func Generate(seed uint64) string {
	g := &gen{r: rand.New(rand.NewPCG(seed, seed^0x9e3779b97f4a7c15)), vars: map[string][]string{}}
	return g.program(seed)
}

func (g *gen) program(seed uint64) string {
	fmt.Fprintf(&g.b, "// Code generated by internal/progen (seed %d). DO NOT EDIT.\n\n", seed)
	g.b.WriteString("package main\n\nimport (\n\t\"fmt\"\n\t\"strconv\"\n\t\"strings\"\n)\n\n")
	for _, t := range allTypes {
		n := 2 + g.r.IntN(2)
		for i := 0; i < n; i++ {
			// Never a prefix of another name: closures replace a name.
			name := fmt.Sprintf("v_%s_%d", short(t), i)
			g.vars[t] = append(g.vars[t], name)
			fmt.Fprintf(&g.b, "var %s %s = %s\n", name, t, g.literal(t))
		}
	}
	g.b.WriteString("var sl = []int64{3, -1, 4, 1, -5, 9, 2, -6}\n")
	g.b.WriteString("var mp = map[string]int64{\"a\": 1, \"b\": -2}\n\n")
	g.b.WriteString(aggDecls)
	// Helpers that keep strconv and strings used.
	g.b.WriteString("func itoa(x int64) string { return strconv.FormatInt(x, 10) }\n\n")
	g.b.WriteString(panicHelpers)
	g.b.WriteString("func up(s string) string { return strings.ToUpper(s) }\n\n")
	nf := 6 + g.r.IntN(5)
	for i := 0; i < nf; i++ {
		fmt.Fprintf(&g.b, "func f%d() {\n", i)
		ns := 4 + g.r.IntN(6)
		for j := 0; j < ns; j++ {
			g.stmt(1)
		}
		g.b.WriteString("}\n\n")
	}
	g.b.WriteString("func run(name string, f func()) {\n\tdefer func() {\n\t\tif r := recover(); r != nil {\n\t\t\tfmt.Println(name, \"panic:\", r)\n\t\t}\n\t}()\n\tf()\n}\n\n")
	g.b.WriteString("func dump() {\n")
	for _, t := range allTypes {
		fmt.Fprintf(&g.b, "\tfmt.Println(%q, %s)\n", t, strings.Join(g.vars[t], ", "))
	}
	g.b.WriteString("\tfmt.Println(sl, mp)\n")
	g.b.WriteString("\tfmt.Println(v_S_0, v_S_1, v_S_2, *v_PS, v_A_0, v_A_1, ms, len(sq), sq)\n}\n\n")
	g.b.WriteString("func main() {\n")
	for i := 0; i < nf; i++ {
		fmt.Fprintf(&g.b, "\trun(%q, f%d)\n\tdump()\n", fmt.Sprintf("f%d", i), i)
	}
	g.b.WriteString("}\n")
	return g.b.String()
}

func short(t string) string {
	switch t {
	case "float64":
		return "f"
	case "bool":
		return "b"
	case "string":
		return "s"
	}
	return t
}

func (g *gen) indent(n int) {
	g.b.WriteString(strings.Repeat("\t", n))
}

// stmt writes one statement at indentation n.
func (g *gen) stmt(n int) {
	g.indent(n)
	switch k := g.r.IntN(16); {
	case k >= 12 && n <= 3:
		g.aggStmt(n)
	case k < 6 || n > 3:
		t := allTypes[g.r.IntN(len(allTypes))]
		fmt.Fprintf(&g.b, "%s = %s\n", g.pick(t), g.expr(t, 0))
	case k == 6:
		fmt.Fprintf(&g.b, "if %s {\n", g.expr("bool", 0))
		g.stmt(n + 1)
		g.indent(n)
		g.b.WriteString("} else {\n")
		g.stmt(n + 1)
		g.indent(n)
		g.b.WriteString("}\n")
	case k == 7:
		fmt.Fprintf(&g.b, "for i := 0; i < %d; i++ {\n", 1+g.r.IntN(4))
		g.indent(n + 1)
		fmt.Fprintf(&g.b, "%s += %s(i)\n", g.pick("int64"), "int64")
		g.stmt(n + 1)
		g.indent(n)
		g.b.WriteString("}\n")
	case k == 8:
		fmt.Fprintf(&g.b, "switch %s %% 3 {\n", g.expr("int64", 0))
		for c := 0; c < 3; c++ {
			g.indent(n)
			if c == 2 {
				g.b.WriteString("default:\n")
			} else {
				fmt.Fprintf(&g.b, "case %d:\n", c)
			}
			g.stmt(n + 1)
		}
		g.indent(n)
		g.b.WriteString("}\n")
	case k == 9:
		t := intTypes[g.r.IntN(len(intTypes))]
		fmt.Fprintf(&g.b, "{\n")
		g.indent(n + 1)
		fmt.Fprintf(&g.b, "c := func(a %s) %s { return %s }\n", t, t, strings.ReplaceAll(g.expr(t, 1), g.pick(t), "a"))
		g.indent(n + 1)
		fmt.Fprintf(&g.b, "%s = c(%s)\n", g.pick(t), g.expr(t, 1))
		g.indent(n)
		g.b.WriteString("}\n")
	case k == 10:
		// Slices: an index that may be out of range, an append.
		fmt.Fprintf(&g.b, "set(%s, %s)\n", g.index(), g.expr("int64", 0))
		g.indent(n)
		fmt.Fprintf(&g.b, "if len(sl) < 20 {\n")
		g.indent(n + 1)
		fmt.Fprintf(&g.b, "sl = append(sl, %s)\n", g.expr("int64", 1))
		g.indent(n)
		g.b.WriteString("}\n")
	default:
		fmt.Fprintf(&g.b, "mp[%s] = %s\n", g.expr("string", 1), g.expr("int64", 1))
		g.indent(n)
		fmt.Fprintf(&g.b, "%s += mp[%s]\n", g.pick("int64"), g.expr("string", 1))
	}
}

// index returns an int index of sl that is out of range now and then.
func (g *gen) index() string {
	if g.r.IntN(6) == 0 {
		return fmt.Sprintf("int(%s) %% 16", g.pick("uint8"))
	}
	return fmt.Sprintf("int(%s %% 8 & 7)", g.pick("uint16"))
}

// pick returns a variable of type t.
func (g *gen) pick(t string) string {
	vs := g.vars[t]
	return vs[g.r.IntN(len(vs))]
}

// literal returns a constant of type t that fits it.
func (g *gen) literal(t string) string {
	switch t {
	case "float64":
		vals := []string{"0.5", "-1.25", "3", "1e10", "-7.75", "0.1", "2.5e-3"}
		return vals[g.r.IntN(len(vals))]
	case "bool":
		return []string{"true", "false"}[g.r.IntN(2)]
	case "string":
		vals := []string{`"go"`, `"vm"`, `""`, `"héllo"`, `"a,b"`, `"xyz"`}
		return vals[g.r.IntN(len(vals))]
	}
	lo, hi := bounds(t)
	switch g.r.IntN(4) {
	case 0:
		return fmt.Sprint(lo)
	case 1:
		return fmt.Sprint(hi)
	}
	small := []int64{0, 1, 2, 3, 7, 100, -1, -3, -100}
	v := small[g.r.IntN(len(small))]
	if v < 0 && lo == 0 {
		v = -v
	}
	return fmt.Sprint(v)
}

// bounds returns the range of the integer type t, with int and uint as 32
// bits: a literal must compile on 32-bit platforms.
func bounds(t string) (lo, hi any) {
	switch t {
	case "int8":
		return -128, 127
	case "int16":
		return -32768, 32767
	case "int32", "int":
		return -2147483648, 2147483647
	case "int64":
		return int64(-9223372036854775808), int64(9223372036854775807)
	case "uint8":
		return 0, 255
	case "uint16":
		return 0, 65535
	case "uint32", "uint":
		return 0, uint64(4294967295)
	}
	return 0, uint64(18446744073709551615)
}

func isInt(t string) bool {
	for _, x := range intTypes {
		if x == t {
			return true
		}
	}
	return false
}

// expr returns a non-constant expression of type t.
func (g *gen) expr(t string, d int) string {
	if d > 3 || g.r.IntN(4) == 0 {
		return g.pick(t)
	}
	switch {
	case isInt(t):
		return g.intExpr(t, d)
	case t == "float64":
		ops := []string{"+", "-", "*", "/"}
		switch g.r.IntN(4) {
		case 0:
			src := intTypes[g.r.IntN(len(intTypes))]
			return fmt.Sprintf("float64(%s)", g.expr(src, d+1))
		case 1:
			return fmt.Sprintf("-%s", g.paren("float64", d))
		}
		// The conversion rounds the result: gc may fuse x*y+z into one
		// FMA instruction (arm64, ppc64le, s390x), as the spec allows,
		// and the VM rounds each operation (see the package comment).
		return fmt.Sprintf("float64(%s %s %s)", g.paren("float64", d), ops[g.r.IntN(len(ops))], g.operand("float64", d))
	case t == "bool":
		switch g.r.IntN(5) {
		case 0:
			return fmt.Sprintf("!%s", g.paren("bool", d))
		case 1:
			return fmt.Sprintf("%s && %s", g.paren("bool", d), g.paren("bool", d))
		case 2:
			return fmt.Sprintf("%s || %s", g.paren("bool", d), g.paren("bool", d))
		}
		ct := allTypes[g.r.IntN(len(allTypes)-1)] // not string: below
		if g.r.IntN(5) == 0 {
			ct = "string"
		}
		cmps := []string{"==", "!=", "<", "<=", ">", ">="}
		if ct == "bool" {
			cmps = cmps[:2]
		}
		return fmt.Sprintf("%s %s %s", g.paren(ct, d), cmps[g.r.IntN(len(cmps))], g.operand(ct, d))
	}
	// string
	switch g.r.IntN(6) {
	case 0:
		return fmt.Sprintf("%s + %s", g.paren("string", d), g.operand("string", d))
	case 1:
		return fmt.Sprintf("itoa(%s)", g.expr("int64", d+1))
	case 2:
		return fmt.Sprintf("up(%s)", g.expr("string", d+1))
	case 3:
		src := allTypes[g.r.IntN(len(allTypes))]
		return fmt.Sprintf("fmt.Sprint(%s)", g.expr(src, d+1))
	case 4:
		// A slice that may be out of range.
		return fmt.Sprintf("sub(%s, int(%s)%%4)", g.pick("string"), g.pick("uint8"))
	}
	return fmt.Sprintf("strconv.Quote(%s)", g.expr("string", d+1))
}

// intExpr returns a non-constant expression of the integer type t.
func (g *gen) intExpr(t string, d int) string {
	switch k := g.r.IntN(10); {
	case k == 0:
		src := intTypes[g.r.IntN(len(intTypes))]
		return fmt.Sprintf("%s(%s)", t, g.expr(src, d+1))
	case k == 1:
		un := []string{"-", "^", "+"}
		return fmt.Sprintf("%s%s", un[g.r.IntN(len(un))], g.paren(t, d))
	case k == 2:
		// A shift with an unsigned count, at times past the width.
		return fmt.Sprintf("%s %s (%s %% 70)", g.paren(t, d), []string{"<<", ">>"}[g.r.IntN(2)], g.pick("uint8"))
	case k == 3:
		// A signed count: inline it is never negative; through shl, a
		// negative count panics.
		if g.r.IntN(2) == 0 {
			return fmt.Sprintf("%s << (%s & 15)", g.paren(t, d), g.pick("int8"))
		}
		return fmt.Sprintf("shl(%s, %s %% 9)", g.expr(t, d+1), g.pick("int8"))
	case k == 4:
		// Never a constant divisor: a constant zero does not compile.
		// Inline the divisor is never zero (|1); through div and rem, a
		// zero divisor panics.
		op := []string{"/", "%"}[g.r.IntN(2)]
		if g.r.IntN(2) == 0 {
			return fmt.Sprintf("%s %s (%s | 1)", g.paren(t, d), op, g.paren(t, d))
		}
		return fmt.Sprintf("%s(%s, %s)", map[string]string{"/": "div", "%": "rem"}[op], g.expr(t, d+1), g.expr(t, d+1))
	case k == 5:
		return fmt.Sprintf("%s(len(%s))", t, g.pick("string"))
	}
	ops := []string{"+", "-", "*", "&", "|", "^", "&^"}
	return fmt.Sprintf("%s %s %s", g.paren(t, d), ops[g.r.IntN(len(ops))], g.operand(t, d))
}

// paren returns a non-constant expression of type t, in parentheses.
func (g *gen) paren(t string, d int) string {
	e := g.expr(t, d+1)
	// "-" before "-x" would be "--x", a decrement.
	if strings.ContainsAny(e, " ") || strings.ContainsAny(e[:1], "-^+!") {
		return "(" + e + ")"
	}
	return e
}

// operand returns the right operand of a binary operator: a variable, a
// literal or an expression. The left operand is never constant, so the
// expression is not constant.
func (g *gen) operand(t string, d int) string {
	if g.r.IntN(3) == 0 {
		return t + "(" + g.literal(t) + ")"
	}
	return g.paren(t, d)
}

// The aggregates of a program: structs with an array, a string and a slice,
// a pointer to one of them, arrays, a map of structs, methods with value and
// pointer receivers, and an interface. The value model of the VM (copies of
// structs and arrays, pointers into them, aliasing of slices) is where it
// differs most from gc.
const aggDecls = `type S struct {
	A int64
	B [3]int32
	C string
	D []int16
}

func (s S) Sum() int64 {
	return s.A + int64(s.B[0]) + int64(s.B[1]) + int64(s.B[2]) + int64(len(s.C)) + int64(len(s.D))
}

func (s *S) Bump(d int64) {
	s.A += d
	s.B[1]++
	s.C += "+"
}

type I interface{ Sum() int64 }

var v_S_0 = S{A: 1, B: [3]int32{1, 2, 3}, C: "s0"}
var v_S_1 = S{A: -2, C: "s1", D: []int16{7}}
var v_S_2 S
var v_PS = &v_S_0
var v_A_0 = [4]int64{1, 2, 3, 4}
var v_A_1 [4]int64
var ms = map[string]S{}
var sq = make([]S, 1, 4)

`

// aggStmt writes a statement over the aggregates, at indentation n.
func (g *gen) aggStmt(n int) {
	sv := func() string { return fmt.Sprintf("v_S_%d", g.r.IntN(3)) }
	idx := func(m int) string { return fmt.Sprintf("int(%s %% %d)", g.pick("uint8"), m) }
	line := func(format string, a ...any) {
		g.indent(n)
		fmt.Fprintf(&g.b, format+"\n", a...)
	}
	// The first line is already indented by stmt.
	g.b.WriteString("{\n")
	n++
	switch g.r.IntN(10) {
	case 0: // a copy of a struct, changed, then stored
		line("x := %s", sv())
		line("x.A = %s", g.expr("int64", 1))
		line("x.B[%s] = %s", idx(3), g.expr("int32", 1))
		line("x.C = %s", g.expr("string", 2))
		line("%s = x", sv())
	case 1: // a pointer to a global struct, and its methods
		line("v_PS = &%s", sv())
		line("v_PS.Bump(%s)", g.expr("int64", 1))
		line("%s.Bump(%s)", sv(), g.expr("int64", 2))
		line("%s += v_PS.Sum() + %s.Sum()", g.pick("int64"), sv())
	case 2: // interfaces holding a value and a pointer
		line("var i I = %s", sv())
		line("var j I = v_PS")
		line("v_PS.Bump(1)")
		line("%s = i.Sum() - j.Sum()", g.pick("int64"))
		line("_, isPtr := j.(*S)")
		line("%s = isPtr", g.pick("bool"))
	case 3: // a pointer to an element of an array field
		line("p := &%s.B[%s]", sv(), idx(3))
		line("*p += %s", g.expr("int32", 1))
		line("q := p")
		line("*q *= 2")
	case 4: // arrays are values
		line("arr := v_A_0")
		line("arr[%s] = %s", idx(4), g.expr("int64", 1))
		line("v_A_1 = arr")
		line("v_A_0[%s]++", idx(4))
		line("%s = arr == v_A_0", g.pick("bool"))
	case 5: // a slice field: append within a bounded length
		v := sv()
		line("if len(%s.D) < 6 {", v)
		line("\t%s.D = append(%s.D, %s)", v, v, g.expr("int16", 1))
		line("}")
		line("%s.D = %s.D[:len(%s.D):len(%s.D)]", v, v, v, v)
	case 6: // aliasing of a slice of structs through its capacity
		line("if len(sq) < 4 {")
		line("\tt := append(sq[:len(sq):cap(sq)], %s)", sv())
		line("\tt[0].A += %s", g.expr("int64", 2))
		line("\tsq = t")
		line("}")
		line("%s = sq[%s]", sv(), idx(4))
	case 7: // a map of structs: values are copies
		k := g.expr("string", 2)
		line("ms[%s] = %s", k, sv())
		line("tmp := ms[%s]", k)
		line("tmp.A++")
		line("tmp.B[%s] = %s", idx(3), g.expr("int32", 2))
		line("ms[%s] = tmp", g.expr("string", 2))
	case 8: // a closure that captures a struct and changes it
		v := sv()
		line("f := func(d int64) int64 { %s.A += d; return %s.Sum() }", v, v)
		line("%s = f(%s) + f(%s)", g.pick("int64"), g.expr("int64", 1), g.expr("int64", 2))
	default: // a struct literal, a comparison of arrays, a method value
		line("y := S{A: %s, C: %s, B: [3]int32{%s, 1}}", g.expr("int64", 1), g.expr("string", 2), g.expr("int32", 2))
		line("m := y.Sum")
		line("y.A = 0")
		line("%s = m() + y.Sum()", g.pick("int64"))
		line("%s = y.B == %s.B", g.pick("bool"), sv())
	}
	n--
	g.indent(n)
	g.b.WriteString("}\n")
}

// panicHelpers are the operations that can panic, as calls: the order of
// calls is the lexical order (see the package comment).
const panicHelpers = `type integer interface {
	~int | ~int8 | ~int16 | ~int32 | ~int64 | ~uint | ~uint8 | ~uint16 | ~uint32 | ~uint64
}

func div[T integer](a, b T) T { return a / b }

func rem[T integer](a, b T) T { return a % b }

func shl[T integer](x T, n int8) T { return x << n }

func sub(s string, n int) string { return s[:n] }

func set(i int, v int64) { sl[i] = v }

`
