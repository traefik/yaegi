// Package gosources holds the manifest of the sources of the standard
// library packages that yaegi v2 copies (the AOT copies of aot/go1_NN), for
// each Go patch release: aot/all/gosources.txt.
//
// The AOT copies are made with one Go patch release. A host built with a
// newer patch release of the same release may still use them when the
// newer patch release did not change the sources of any copied package:
// the copies are then the same code as the standard library of the host.
// The manifest records, for each Go version, the hash (internal/srchash) of
// the GOROOT sources of each copied package, so that the VM can compare
// two versions without the GOROOT (vm/aotversion.go).
//
// cmd/aotgen writes the entry of the Go version it runs with; cmd/aotgosrc
// adds the entries of the newer patch releases (CI job "Go patch
// releases"). Like internal/gorelease, this package must not import the
// generated packages.
package gosources

import (
	"bufio"
	"bytes"
	"errors"
	"fmt"
	"io/fs"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/traefik/yaegi/v2/internal/gorelease"
	"github.com/traefik/yaegi/v2/internal/srchash"
)

// Absent is the hash of a package that a Go version does not have.
const Absent = "-"

// Manifest maps a Go version ("go1.27.3") to the hash of the sources of
// each copied standard package of its release ("encoding/json" ->
// "s1:..."). The packages of one release are the same in each of its
// versions.
type Manifest map[string]map[string]string

// Header is the first lines of the manifest file.
const Header = `# Code generated by cmd/aotgen and cmd/aotgosrc. DO NOT EDIT.
# The hash (internal/srchash) of the GOROOT sources of each standard package
# that yaegi v2 copies (aot/go1_NN), for each Go version: "version package hash".
# A host built with a newer patch release than the AOT copies may use them
# when every hash is the same (vm/aotversion.go, internal/gosources).
`

// Parse reads a manifest file.
func Parse(data []byte) (Manifest, error) {
	m := Manifest{}
	sc := bufio.NewScanner(bytes.NewReader(data))
	for n := 1; sc.Scan(); n++ {
		line := strings.TrimSpace(sc.Text())
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		f := strings.Fields(line)
		if len(f) != 3 {
			return nil, fmt.Errorf("gosources: line %d: want \"version package hash\": %q", n, line)
		}
		if _, ok := gorelease.Patch(f[0]); !ok {
			return nil, fmt.Errorf("gosources: line %d: bad Go version %q", n, f[0])
		}
		if m[f[0]] == nil {
			m[f[0]] = map[string]string{}
		}
		if _, dup := m[f[0]][f[1]]; dup {
			return nil, fmt.Errorf("gosources: line %d: %s %s twice", n, f[0], f[1])
		}
		m[f[0]][f[1]] = f[2]
	}
	return m, sc.Err()
}

// Format writes m as a manifest file, sorted by version and package.
func (m Manifest) Format() []byte {
	var b bytes.Buffer
	b.WriteString(Header)
	vs := make([]string, 0, len(m))
	for v := range m {
		vs = append(vs, v)
	}
	sort.Slice(vs, func(i, j int) bool { return Less(vs[i], vs[j]) })
	for _, v := range vs {
		ps := make([]string, 0, len(m[v]))
		for p := range m[v] {
			ps = append(ps, p)
		}
		sort.Strings(ps)
		for _, p := range ps {
			fmt.Fprintf(&b, "%s %s %s\n", v, p, m[v][p])
		}
	}
	return b.Bytes()
}

// Less orders Go versions by release, then betas, release candidates and
// patch releases (gorelease.Compare, the order of vm/aotversion.go):
// go1.27rc2 < go1.27.0. Two names of the same version are ordered as
// strings.
func Less(a, b string) bool {
	if c := gorelease.Compare(a, b); c != 0 {
		return c < 0
	}
	return a < b
}

// Same reports whether Go version host has the same sources as Go version
// copies for every copied package of copies. changed lists the packages
// whose sources differ; known is false when one of the two versions is not
// in m (then the sources are not known to be the same). GOEXPERIMENT
// suffixes are ignored.
func (m Manifest) Same(copies, host string) (same bool, changed []string, known bool) {
	c, h := m[gorelease.StripExperiments(copies)], m[gorelease.StripExperiments(host)]
	if len(c) == 0 || len(h) == 0 {
		return false, nil, false
	}
	for p, hash := range c {
		if h[p] != hash {
			changed = append(changed, p)
		}
	}
	sort.Strings(changed)
	return len(changed) == 0, changed, true
}

// StdCopies returns the standard packages copied in tree (aot/go1_NN): the
// directories with Go files whose first path element has no dot, except
// "all" (the registration package of yaegi v2) and the directories that the
// go command ignores (_failed, the quarantine of aotgen).
func StdCopies(tree string) ([]string, error) {
	seen := map[string]bool{}
	err := filepath.WalkDir(tree, func(path string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if d.IsDir() {
			// The go command ignores "_failed" (the quarantine of aotgen),
			// ".x" and testdata.
			if n := d.Name(); path != tree && (strings.HasPrefix(n, "_") || strings.HasPrefix(n, ".") || n == "testdata") {
				return filepath.SkipDir
			}
			return nil
		}
		if !strings.HasSuffix(path, ".go") {
			return nil
		}
		rel, err := filepath.Rel(tree, filepath.Dir(path))
		if err != nil {
			return err
		}
		rel = filepath.ToSlash(rel)
		first, _, _ := strings.Cut(rel, "/")
		if rel == "." || rel == "all" || strings.Contains(first, ".") {
			return nil
		}
		seen[rel] = true
		return nil
	})
	if err != nil {
		return nil, err
	}
	out := make([]string, 0, len(seen))
	for p := range seen {
		out = append(out, p)
	}
	sort.Strings(out)
	if len(out) == 0 {
		return nil, fmt.Errorf("gosources: no copied standard package in %s", tree)
	}
	return out, nil
}

// Hash returns the hash of the sources of each package of pkgs in the
// GOROOT goroot (srchash.Dir of <goroot>/src/<package>), or Absent.
func Hash(goroot string, pkgs []string) (map[string]string, error) {
	out := make(map[string]string, len(pkgs))
	for _, p := range pkgs {
		h, err := srchash.Dir(filepath.Join(goroot, "src", filepath.FromSlash(p)))
		if errors.Is(err, fs.ErrNotExist) {
			h = Absent
		} else if err != nil {
			return nil, err
		}
		out[p] = h
	}
	return out, nil
}

// ReadFile reads the manifest file at path; a missing file is an empty
// manifest.
func ReadFile(path string) (Manifest, error) {
	b, err := os.ReadFile(path)
	if errors.Is(err, fs.ErrNotExist) {
		return Manifest{}, nil
	}
	if err != nil {
		return nil, err
	}
	return Parse(b)
}

// Record sets the entry of Go version v (its packages pkgs hashed in goroot)
// in the manifest file at path. With prune, it also removes the versions of
// the release of v that are older than v (the AOT copies are now made with
// v), and the versions of the releases outside the window of yaegi v2.
func Record(path, v, goroot string, pkgs []string, prune bool) error {
	m, err := ReadFile(path)
	if err != nil {
		return err
	}
	h, err := Hash(goroot, pkgs)
	if err != nil {
		return err
	}
	v = gorelease.StripExperiments(v)
	if prune {
		for old := range m {
			if !gorelease.InWindow(old) || gorelease.Release(old) == gorelease.Release(v) && Less(old, v) {
				delete(m, old)
			}
		}
	}
	m[v] = h
	return os.WriteFile(path, m.Format(), 0o644)
}
