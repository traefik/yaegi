// fill sets struct fields of *Config by name (what Traefik does with mapstructure).
func fill(cfg reflect.Value, fields map[string]any) {
	for k, v := range fields {
		f := cfg.Elem().FieldByName(k)
		f.Set(reflect.ValueOf(v).Convert(f.Type()))
	}
}

// ---- next handlers ----

// benchNext is the downstream handler during benchmarks: minimal native work.
var benchNext = http.HandlerFunc(func(rw http.ResponseWriter, req *http.Request) { rw.WriteHeader(http.StatusOK) })

// checkNext dumps what the plugin forwarded, for correctness comparison.
var checkNext = http.HandlerFunc(func(rw http.ResponseWriter, req *http.Request) {
	var b strings.Builder
	fmt.Fprintf(&b, "next: %s %s\n", req.Method, req.URL.Path)
	keys := make([]string, 0, len(req.Header))
	for k := range req.Header {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	for _, k := range keys {
		fmt.Fprintf(&b, "  %s: %s\n", k, strings.Join(req.Header[k], ","))
	}
	rw.WriteHeader(http.StatusOK)
	_, _ = io.WriteString(rw, b.String())
})

// ---- loaders ----

type loaded struct {
	h      http.Handler
	detail string
	vm     *vm.Plugin
}

func benchDir() string {
	exe, _ := os.Getwd()
	return exe
}

var yaegiGoPath string

// goPathForYaegi returns a temporary GOPATH whose src/plugins links to the
// plugins/ directory of this repository: yaegi resolves "plugins/<name>"
// through GOPATH, as Traefik does with its plugin cache.
func goPathForYaegi() (string, error) {
	if yaegiGoPath != "" {
		return yaegiGoPath, nil
	}
	dir, err := os.MkdirTemp("", "yaegi-bench-gopath")
	if err != nil {
		return "", err
	}
	if err := os.MkdirAll(filepath.Join(dir, "src"), 0o755); err != nil {
		return "", err
	}
	if err := os.Symlink(filepath.Join(benchDir(), "plugins"), filepath.Join(dir, "src", "plugins")); err != nil {
		return "", err
	}
	yaegiGoPath = dir
	return dir, nil
}

func load(w *workload, cfg string, next http.Handler) (*loaded, error) {
	switch cfg {
	case "native":
		h, err := w.native(w, next)
		return &loaded{h: h}, err
	case "yaegi":
		gopath, err := goPathForYaegi()
		if err != nil {
			return nil, err
		}
		i := interp.New(interp.Options{GoPath: gopath})
		if err := i.Use(stdlib.Symbols); err != nil {
			return nil, err
		}
		if _, err := i.Eval(fmt.Sprintf("import %q", "plugins/"+w.short)); err != nil {
			return nil, err
		}
		cc, err := i.Eval(w.short + ".CreateConfig")
		if err != nil {
			return nil, err
		}
		c := cc.Call(nil)[0]
		fill(c, w.config)
		nf, err := i.Eval(w.short + ".New")
		if err != nil {
			return nil, err
		}
		out := nf.Call([]reflect.Value{reflect.ValueOf(context.Background()), reflect.ValueOf(next), c, reflect.ValueOf(w.short)})
		if !out[1].IsNil() {
			return nil, out[1].Interface().(error)
		}
		return &loaded{h: out[0].Interface().(http.Handler)}, nil
	case "vm-native", "vm-src", "vm-mixed", "vm-aot", "vm-aotall":
		opts := vm.Options{Dir: benchDir()}
		switch cfg {
		case "vm-src":
			opts.Src, opts.OpaqueAny = w.src, true
		case "vm-mixed":
			opts.Src, opts.OpaqueAny = w.mixed, true
		case "vm-aot":
			opts.Modes = map[string]vm.Mode{"encoding/json": vm.ModeAOT}
		case "vm-aotall":
			opts.AOT = true
		}
		if s := os.Getenv("VM_SRC"); s != "" {
			opts.Src = strings.Split(s, ",")
		}
		if os.Getenv("VM_LIMITS") != "" {
			// The limits of the catalog host (internal/pluginhost), to
			// measure their cost.
			ho := pluginhost.Options()
			opts.Budget, opts.BackgroundRate, opts.MaxGoroutines = ho.Budget, ho.BackgroundRate, ho.MaxGoroutines
			opts.PanicOnFatal, opts.MaxMemory = ho.PanicOnFatal, ho.MaxMemory
		}
		if s := os.Getenv("VM_BUDGET"); s != "" {
			b, err := strconv.ParseInt(s, 10, 64)
			if err != nil {
				return nil, err
			}
			opts.Budget = b
		}
		var p *vm.Plugin
		var err error
		if prev := vmCache[cfg]; prev != nil && useCache {
			p, err = prev.LoadCached(filepath.Join(benchDir(), "plugins", w.short), opts)
		} else {
			p, err = vm.Load(opts, w.pkg)
			vmCache[cfg] = p
		}
		if err != nil {
			return nil, err
		}
		c, err := pluginhost.CreateConfig(p)
		if err != nil {
			return nil, err
		}
		if err := c.SetFields(w.config); err != nil {
			return nil, err
		}
		h, err := pluginhost.NewHandler(context.Background(), p, next, c, w.short)
		if err != nil {
			return nil, err
		}
		return &loaded{h: h, vm: p, detail: fmt.Sprintf("load=%v ssa=%v init=%v", p.LoadTime.Round(time.Millisecond), p.BuildTime.Round(time.Millisecond), p.InitTime.Round(time.Millisecond))}, nil
	}
	return nil, fmt.Errorf("unknown config %q", cfg)
}

// vmCache keeps the first VM load of each configuration: later loads (warm,
// benchmark handler) use vm.LoadCached, i.e. a process-wide cache of stdlib
// types and SSA, as a production VM would embed.
var (
	vmCache  = map[string]*vm.Plugin{}
	useCache = os.Getenv("VM_NOCACHE") == ""
)

// ---- request driving ----

func serve(h http.Handler, w *workload, base *http.Request) (rec *httptest.ResponseRecorder, err error) {
	defer func() {
		if r := recover(); r != nil {
			err = fmt.Errorf("panic: %v", r)
		}
	}()
	r := *base
	r.Header = base.Header.Clone()
	u := *base.URL
	r.URL = &u
	if w.name == "w2-json" {
		r.Body = io.NopCloser(bytes.NewReader(jsonBody))
	}
	rec = httptest.NewRecorder()
	h.ServeHTTP(rec, &r)
	return rec, nil
}

func dump(rec *httptest.ResponseRecorder) string {
	var b strings.Builder
	fmt.Fprintf(&b, "status %d\n", rec.Code)
	keys := slices.Sorted(func(yield func(string) bool) {
		for k := range rec.Header() {
			if !yield(k) {
				return
			}
		}
	})
	for _, k := range keys {
		fmt.Fprintf(&b, "%s: %s\n", k, strings.Join(rec.Header()[k], ","))
	}
	b.WriteString(rec.Body.String())
	return b.String()
}

func maxRSS() int64 {
	var ru syscall.Rusage
	_ = syscall.Getrusage(syscall.RUSAGE_SELF, &ru)
	return int64(ru.Maxrss) // bytes on darwin (int32 on 32-bit linux)
}

type cfgRun struct {
	name     string
	h        http.Handler
	n        int
	cpu, ns  []float64
	allocs   []float64
	bytes    []float64
	verdict  string
	loadCold time.Duration
	loadWarm time.Duration
	heapKB   int64
	detail   string
}

func cpuTime() time.Duration {
	var ru syscall.Rusage
	_ = syscall.Getrusage(syscall.RUSAGE_SELF, &ru)
	return time.Duration(ru.Utime.Nano() + ru.Stime.Nano())
}

// measure runs n requests and returns wall ns/op, CPU ns/op (user+sys of the
// whole process, GC included), allocs/op and B/op.
func measure(h http.Handler, w *workload, base *http.Request, n int) (ns, cpu, allocs, bytes float64) {
	var a, b runtime.MemStats
	runtime.GC()
	runtime.ReadMemStats(&a)
	c0, t0 := cpuTime(), time.Now()
	for i := 0; i < n; i++ {
		if _, err := serve(h, w, base); err != nil {
			panic(err)
		}
	}
	wall, c := time.Since(t0), cpuTime()-c0
	runtime.ReadMemStats(&b)
	f := float64(n)
	return float64(wall.Nanoseconds()) / f, float64(c.Nanoseconds()) / f, float64(b.Mallocs-a.Mallocs) / f, float64(b.TotalAlloc-a.TotalAlloc) / f
}

func main() {
	wname := flag.String("w", "w1", "workload: w1|w2|w3")
	cfgs := flag.String("cfg", "native", "comma-separated configurations (measured round-robin)")
	count := flag.Int("count", 10, "benchmark repetitions per configuration")
	benchtime := flag.Duration("benchtime", 300*time.Millisecond, "duration per repetition")
	cpuprof := flag.String("cpuprofile", "", "write CPU profile of the benchmark loop (use with a single cfg)")
	showOut := flag.Bool("show", false, "print the checked output")
	memprof := flag.String("memprofile", "", "write an allocation profile after the benchmark loop")
	vmprof := flag.Int("vmprof", 0, "VM_PROFILE=1 only: run N requests and print the VM instruction profile")
	flag.Parse()

	w := workloads[*wname]
	if w == nil {
		fmt.Fprintln(os.Stderr, "unknown workload")
		os.Exit(2)
	}
	base := w.request()
	if os.Getenv("VM_CANCELCTX") != "" {
		// A context that can be canceled, as the requests of a real
		// server have: the VM ties each ServeHTTP to it (vm/budget.go).
		ctx, cancel := context.WithCancel(context.Background())
		defer cancel()
		base = base.WithContext(ctx)
	}

	// Reference output (native, compiled into this host).
	refH, err := w.native(w, checkNext)
	if err != nil {
		panic(err)
	}
	refRec, _ := serve(refH, w, base)
	ref := dump(refRec)

	var runs []*cfgRun
	for _, cfg := range strings.Split(*cfgs, ",") {
		r := &cfgRun{name: cfg}
		if cfg == "baseline" { // host overhead only: request copy + recorder + minimal next
			r.h, r.verdict = benchNext, "-"
			runs = append(runs, r)
			continue
		}
		// Load (timed): source -> first handler ready. First load of this
		// config in the process ("cold"), then a second one ("warm").
		var ms0, ms1 runtime.MemStats
		runtime.GC()
		runtime.ReadMemStats(&ms0)
		t0 := time.Now()
		lc, err := load(w, cfg, checkNext)
		r.loadCold = time.Since(t0)
		if err != nil {
			fmt.Printf("%s\t%s\tLOADFAIL\t%v\n", w.name, cfg, oneLine(err.Error()))
			continue
		}
		runtime.GC()
		runtime.ReadMemStats(&ms1)
		r.heapKB = (int64(ms1.HeapAlloc) - int64(ms0.HeapAlloc)) / 1024
		r.detail = lc.detail
		t1 := time.Now()
		if _, err := load(w, cfg, checkNext); err != nil {
			panic(err)
		}
		r.loadWarm = time.Since(t1)

		// Correctness against the native reference.
		rec, err := serve(lc.h, w, base)
		r.verdict = "MATCH"
		got := ""
		if err != nil {
			r.verdict, got = "FAIL", err.Error()
		} else if got = dump(rec); got != ref {
			r.verdict = "DIFF"
		}
		if *showOut || r.verdict != "MATCH" {
			fmt.Fprintf(os.Stderr, "---- %s %s: %s\n--- want:\n%s\n--- got:\n%s\n", w.name, cfg, r.verdict, ref, got)
		}
		if r.verdict == "FAIL" {
			fmt.Printf("%s\t%s\tRUNFAIL\t%v\n", w.name, cfg, oneLine(got))
			continue
		}
		lb, err := load(w, cfg, benchNext)
		if err != nil {
			panic(err)
		}
		r.h = lb.h
		if *vmprof > 0 && lb.vm != nil {
			measure(lb.h, w, base, 20)
			lb.vm.M.ResetProfile()
			measure(lb.h, w, base, *vmprof)
			fmt.Printf("== VM profile %s %s\n", w.name, cfg)
			lb.vm.M.DumpProfile(os.Stdout, *vmprof)
			continue
		}
		runs = append(runs, r)
	}

	// Calibrate n per config for ~benchtime, then measure round-robin so that
	// machine noise affects every configuration alike.
	for _, r := range runs {
		measure(r.h, w, base, 20) // warm-up: lazy compilation, caches
		n := 1
		for {
			t := time.Now()
			measure(r.h, w, base, n)
			if el := time.Since(t); el > *benchtime/10 || n > 1<<24 {
				r.n = max(1, int(float64(n)*float64(*benchtime)/float64(el)))
				break
			}
			n *= 4
		}
	}
	if *cpuprof != "" {
		f, _ := os.Create(*cpuprof)
		_ = pprof.StartCPUProfile(f)
		defer pprof.StopCPUProfile()
	}
	for c := 0; c < *count; c++ {
		for _, r := range runs {
			ns, cpu, al, by := measure(r.h, w, base, r.n)
			r.ns, r.cpu, r.allocs, r.bytes = append(r.ns, ns), append(r.cpu, cpu), append(r.allocs, al), append(r.bytes, by)
		}
	}
	if *memprof != "" {
		f, _ := os.Create(*memprof)
		_ = pprof.Lookup("allocs").WriteTo(f, 0)
		f.Close()
	}
	// workload cfg verdict wall_med wall_min cpu_med cpu_min cpu_max allocs B/op load_cold_ms load_warm_ms heap_load_KB n detail
	for _, r := range runs {
		fmt.Printf("%s\t%s\t%s\t%.0f\t%.0f\t%.0f\t%.0f\t%.0f\t%.1f\t%.0f\t%.1f\t%.1f\t%d\t%d\t%s\n",
			w.name, r.name, r.verdict, median(r.ns), slices.Min(r.ns), median(r.cpu), slices.Min(r.cpu), slices.Max(r.cpu),
			median(r.allocs), median(r.bytes),
			float64(r.loadCold.Microseconds())/1000, float64(r.loadWarm.Microseconds())/1000, r.heapKB, r.n, r.detail)
	}
	fmt.Fprintf(os.Stderr, "maxrss_MB\t%.1f\n", float64(maxRSS())/(1<<20))
}

func median(xs []float64) float64 {
	s := slices.Clone(xs)
	slices.Sort(s)
	n := len(s)
	if n%2 == 1 {
		return s[n/2]
	}
	return (s[n/2-1] + s[n/2]) / 2
}

func oneLine(s string) string {
	s = strings.ReplaceAll(s, "\n", " | ")
	if len(s) > 300 {
		s = s[:300] + "..."
	}
	return s
}
