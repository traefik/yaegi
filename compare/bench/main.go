//go:build unix

// Command bench runs a Traefik-like host that loads one plugin (workload) in
// one configuration and measures load time, per-request cost and correctness.
//
// Configurations:
//
//	native     plugin compiled into the host (reference)
//	yaegi      yaegi v0 (version pinned in compare/go.mod): interp.New + Use(stdlib.Symbols) + Eval, as Traefik does
//	vm-native  spike VM, whole stdlib native (boundary at each call)
//	vm-src     spike VM, stdlib packages used by the plugin interpreted from source
//	vm-mixed   spike VM, only packages that must see plugin types interpreted
//	vm-aot     spike VM, stdlib native, encoding/json replaced by its AOT copy
//	           (aot/encoding/json, generated by cmd/aotgen) that walks VM values
//	           through the VM reflect twin
//	vm-aotall  spike VM, every package generated by cmd/aotgen in AOT mode
//	           (encoding/json, fmt, errors, sort, text/template...)
