// Command vmhost loads a Traefik plugin with yaegi v2 (vm.Load, the default mode
// or -aot) and runs the catalog scenario of driver.go. "vmhost hostile" runs
// the hostile corpus instead (hostile.go).
package main

import (
	"context"
	"errors"
	"flag"
	"net/http"
	"os"

	_ "github.com/traefik/yaegi/v2/aot/all" // AOT copies generated by cmd/aotgen (-aot)
	"github.com/traefik/yaegi/v2/internal/pluginhost"
	_ "github.com/traefik/yaegi/v2/natsyms/all" // native symbol tables of non-std packages
	"github.com/traefik/yaegi/v2/vm"
)

var (
	aot     = flag.Bool("aot", false, "run the packages of aot/ in AOT mode")
	execOpt = flag.String("exec", "", "os/exec of the plugin: \"\" (refused, the default), \"mock\" (Options.Exec = vm.ExecMock)")
	sandbox = flag.Bool("sandbox", false, "load with an Options.Sandbox (sandboxOptions)")
)

// sandboxOptions gives opts a Sandbox with the limits of opts (budget,
// goroutines, the empty environment): the plugin may read its directory and
// the temporary directory, write in the temporary directory, and dial the
// local servers of the runner (127.0.0.1). The reloadsandbox scenario of the
// catalog runs the reloads with it.
func sandboxOptions(opts *vm.Options) {
	opts.Sandbox = &vm.Sandbox{
		Env:           opts.Env,
		ReadPaths:     []string{opts.Dir, os.TempDir()},
		WritePaths:    []string{os.TempDir()},
		DialHosts:     []string{"127.0.0.1", "localhost"},
		Budget:        opts.Budget,
		MaxGoroutines: opts.MaxGoroutines,
		GoPanic:       opts.GoPanic,
	}
}

type vmEngine struct{ p *vm.Plugin }

func (e *vmEngine) load(dir, imp, _ string, useUnsafe bool) error {
	// The limits of a host that loads plugins it does not trust, the mode of the run.
	opts := pluginhost.Options()
	opts.Dir, opts.AOT, opts.UseUnsafe = dir, *aot, useUnsafe
	switch *execOpt {
	case "":
	case "mock":
		opts.Exec = vm.ExecMock
	default:
		return errors.New("-exec: unknown value " + *execOpt)
	}
	if *sandbox {
		sandboxOptions(&opts)
	}
	p, err := vm.Load(opts, imp)
	if err != nil {
		return err
	}
	if p.Pkg.Func("CreateConfig") == nil || p.Pkg.Func("New") == nil {
		return errors.New("no CreateConfig or New")
	}
	e.p = p
	return nil
}

func (e *vmEngine) createConfig(testData map[string]any) (any, error) {
	cfg, err := pluginhost.CreateConfig(e.p)
	if err != nil {
		return nil, err
	}
	if len(testData) > 0 {
		if err := cfg.Decode(func(ptr any) error { return traefikDecode(ptr, testData) }); err != nil {
			return nil, err
		}
	}
	return cfg, nil
}

func (e *vmEngine) newHandler(ctx context.Context, next http.Handler, cfg any, name string) (http.Handler, error) {
	return pluginhost.NewHandler(ctx, e.p, next, cfg.(*vm.Object), name)
}

func main() {
	if len(os.Args) > 1 && os.Args[1] == "hostile" {
		os.Exit(hostileMain(os.Args[2:])) // the hostile corpus (hostile.go)
	}
	newEngine = func() engine { return &vmEngine{} }
	runMain(&vmEngine{})
}
