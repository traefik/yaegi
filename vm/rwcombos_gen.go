//go:build ignore

// rwcombos_gen writes zz_rwcombos.go: one wrapper type per combination of
// the optional ResponseWriter features of rwwriter.go. Run it with
// "go generate ./vm".
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"log"
	"os"
	"strings"
)

// rare and ctl are the bits of ReadFrom|Push|CloseNotify and of the four
// control methods: rwComboMask (rwwriter.go) never uses a mask with a rare
// bit and only some control bits, so these combinations are not made.
const (
	rare = 1<<2 | 1<<3 | 1<<4
	ctl  = 0xf << 6
)

// feats must follow the bit order of the rw* constants of rwwriter.go.
var feats = []struct{ name, field string }{
	{"Flush", "rwFlushW{b.o}"},
	{"Hijack", "rwHijackW{b.o}"},
	{"ReadFrom", "rwReadFromW{b.o}"},
	{"Push", "rwPushW{b.o}"},
	{"CloseNotify", "rwCloseNotifyW{b.o}"},
	{"Unwrap", "rwUnwrapW{b.o}"},
	{"FlushError", "rwFlushErrorW{b}"},
	{"SetReadDeadline", "rwSetReadDeadlineW{b}"},
	{"SetWriteDeadline", "rwSetWriteDeadlineW{b}"},
	{"EnableFullDuplex", "rwEnableFullDuplexW{b}"},
}

func main() {
	n := 1 << len(feats)
	var types, makers bytes.Buffer
	for mask := 0; mask < n; mask++ {
		if mask == 0 {
			fmt.Fprintf(&makers, "func(b rwBase) http.ResponseWriter { return b },\n")
			continue
		}
		if mask&rare != 0 && mask&ctl != 0 && mask&ctl != ctl {
			fmt.Fprintf(&makers, "nil,\n")
			continue
		}
		var embeds, names, lits []string
		for i, f := range feats {
			if mask&(1<<i) != 0 {
				typ := f.field[:strings.IndexByte(f.field, '{')]
				embeds = append(embeds, typ)
				names = append(names, f.name)
				lits = append(lits, f.field)
			}
		}
		name := fmt.Sprintf("rwC%d", mask)
		fmt.Fprintf(&types, "type %s struct { // %s\nrwBase\n%s\n}\n\n", name, strings.Join(names, ", "), strings.Join(embeds, "\n"))
		fmt.Fprintf(&makers, "func(b rwBase) http.ResponseWriter { return %s{b, %s} },\n", name, strings.Join(lits, ", "))
	}
	var out bytes.Buffer
	fmt.Fprintf(&out, "// Code generated by rwcombos_gen.go; DO NOT EDIT.\n\npackage vm\n\nimport \"net/http\"\n\n")
	out.Write(types.Bytes())
	fmt.Fprintf(&out, "// rwCombos makes the wrapper of each feature mask (rwwriter.go).\nvar rwCombos = [1 << rwNumFeat]func(b rwBase) http.ResponseWriter{\n")
	out.Write(makers.Bytes())
	fmt.Fprintf(&out, "}\n")
	src, err := format.Source(out.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("zz_rwcombos.go", src, 0o644); err != nil {
		log.Fatal(err)
	}
}
